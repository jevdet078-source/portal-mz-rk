// Автонапоминание для портала МЗ РК. Подключено хуком в .claude/settings.json проекта:
// UserPromptSubmit (по тексту сообщения) и SessionStart после сжатия контекста.
// Читает JSON из stdin и решает, какое напоминание подставить Claude. Ничего не пишет на диск,
// в сеть не ходит. Если совпадений нет, молчит.
'use strict';

let raw = '';
process.stdin.setEncoding('utf8');
process.stdin.on('data', (c) => { raw += c; });
process.stdin.on('end', () => {
  let data = {};
  try { data = JSON.parse(raw || '{}'); } catch (e) { data = {}; }
  const event = data.hook_event_name || 'UserPromptSubmit';
  const ctx = event === 'SessionStart' ? afterCompact() : forPrompt(String(data.prompt || ''));
  if (!ctx) process.exit(0);
  process.stdout.write(JSON.stringify({ hookSpecificOutput: { hookEventName: event, additionalContext: ctx } }));
});

function afterCompact() {
  return [
    '[Портал МЗ РК] Контекст сжат. Если идёт задача по постановке — перечитать скиллы portal-task и portal-ux (инструментом Skill) и файл docs/tz/… текущей задачи, прежде чем продолжать.',
    'Презентация — перечитать portal-deck. Закрытие (выгрузка, PR, main, отчёт) — portal-finish.',
  ].join('\n');
}

function forPrompt(t) {
  const s = t.toLowerCase().replace(/ё/g, 'е');
  const has = (re) => re.test(s);
  if (s.startsWith('/portal-')) return ''; // скилл вызван явно — он сам всё скажет

  // 1. «Запомни как правило»
  if (has(/запомни|впредь|больше так не делай|не повторяй (эту|такие) ошибк/)) {
    return '[Портал МЗ РК] Пользователь просит запомнить правило. Записать его в каталог .claude/skills/portal-ux/references/defects.md (что было, причина, как не допустить, как проверить), а если правило общее — ещё и в правила SKILL.md нужного скилла (portal-ux / portal-deck / portal-finish). Это в git, поэтому работает с любого аккаунта. Память (memory) — только для фактов о пользователе и проекте.';
  }

  // 2. Презентация
  if (has(/\.pptx|презентац|слайд|deck|министр[уа]? .*(показ|слайд)/)) {
    return '[Портал МЗ РК] Это презентация — работать по скиллу portal-deck (загрузить инструментом Skill): текст строго из исходника, столько же слайдов, варианты не затирать, проверка рендером и сверкой фраз, PDF из 4K, редактируемый PPTX — по запросу.';
  }

  // 3. Постановка / ТЗ / замечания — раньше закрытия: «внеси замечания и залей в main» — это задача целиком
  const isTask = has(/\.(docx|doc|pdf|bpmn|xsd)\b|figma\.com|portal\.isapp/) ||
    has(/(^|[^а-я])(тз|пз)([^а-я]|$)/) ||
    has(/постановк|замечани|доработ|реализ(уй|овать|уем)|новый раздел|новый модуль|референс|stitch|после тестирован/);
  if (isTask) {
    return [
      '[Портал МЗ РК] Это постановка — работать строго по скиллу portal-task (загрузить инструментом Skill) и первым шагом загрузить portal-ux.',
      'Первая строка ответа — «Скиллы: portal-task, portal-ux · тип: … · роль: … · пунктов ТЗ: N».',
      'Файлы читать скриптами docx-extract.cjs / doc-extract.mjs и открыть каждую картинку. Сначала прочитать и подумать, потом код. Финальная проверка — протокол portal-ux/references/final-check.md целиком. Закрытие — portal-finish.',
    ].join('\n');
  }

  // 4. Закрытие задачи
  if (has(/залей в main|влей в main|смерж|сделай (pr|пиар)|выгрузк[уа] html|обнови выгрузку|отчет (о проделанной|для аналитик|аналитику)|текст[- ]отчет|в телеграм/)) {
    return '[Портал МЗ РК] Закрытие — по скиллу portal-finish: выгрузка (export.mjs + export-check.mjs) → push → PR → main → проверка, что main и выгрузка совпадают → отчёт одним блоком ```text для Telegram (мужской род, к аналитику на «вы», без упоминания телефонов). Строка проверки — перед отчётом.';
  }

  // 5. Видео
  if (has(/видео|запиши ролик|mp4|озвучк/)) {
    return '[Портал МЗ РК] Видео — по скиллу portal-video: голос Microsoft Remy (--voice --tts=edge --no-subs), только сценарии этой задачи, английские термины в озвучке латиницей.';
  }

  // 6. Правка интерфейса без файла
  if (has(/экран|модалк|окн[оаеу]|таблиц|колонк|кнопк|отступ|шапк|хедер|header|сайдбар|sidebar|фильтр|вкладк|таб|карточк|бейдж|badge|ховер|hover|скролл|прокрутк|выпадаш|растян|ширин|криво|вылез|поправ|исправ|переделай|перенеси|убери|главн(ая|ой) страниц/)) {
    return '[Портал МЗ РК] Если это правка интерфейса — работать по portal-ux: найти тот же элемент во всех экранах раздела, после правки — финальная проверка (автоаудит, 1440/1366/1920/2560, взгляд глазами), строка проверки, затем portal-finish. Если это просто вопрос — напоминание не применять.';
  }
  return '';
}
