/**
 * Видео «Меню кабинета бизнеса и „Мои заявки“» — постановка от 29.10.2026.
 *
 *   npm run record -- biz-menu-requests   → exports/video/23. Меню кабинета бизнеса и «Мои заявки».mp4
 *
 * Порядок пунктов меню, раскрывающиеся «Услуги» с категориями, внешние переходы ↗,
 * окно «Выберите направление» (КНФ · Цены · ЕД · АЛО), страница «Мои заявки»:
 * фильтры, ошибка периода, сортировка, пагинация, меню действий, пустые состояния,
 * загрузка и ошибка загрузки с повтором.
 */

export const title = 'Меню кабинета бизнеса и «Мои заявки»';
export const fileName = '23. Меню кабинета бизнеса и «Мои заявки»';
export const start = 'Кабинет бизнеса.dc.html';

export default async function record(ctx) {
  const { page, sleep, say, title: card, click, point, type, waitText, open, section } = ctx;

  await card('Портал МЗ РК · постановка аналитика', 'Меню кабинета бизнеса и «Мои заявки»',
    'Новый порядок меню, услуги по категориям, выбор направления и единый список заявок.', 5200);

  // ── 1. Структура меню ─────────────────────────────────────────────
  await section('меню', async () => {
    await open('Кабинет бизнеса.dc.html', { reset: true });
    await waitText('Мои заявки', 15000);
    await card('Пункт 1', 'Структура основного меню', 'Главная · Услуги · Мои заявки · Договоры · Платежи.');
    await point('Главная', 'a.bn-it');
    await say('Порядок пунктов', 'Главная, Услуги, Мои заявки, Договоры, Платежи — как в постановке', 3800);
    await point('Мои заявки', 'a.bn-it');
    await say('Мои заявки', 'Отдельный пункт без вложенного меню — открывает общую страницу заявок', 3600);
    await click('Услуги', 'button.bn-it');
    await sleep(500);
    await say('Услуги свёрнуты', '«Услуги» — раскрывающийся раздел; состояние групп запоминается', 3200);
    await click('Услуги', 'button.bn-it');
    await sleep(500);
    await say('Услуги раскрыты', 'Внутри — две раскрывающиеся категории', 3000);
  });

  // ── 2. Категории ──────────────────────────────────────────────────
  await section('категории', async () => {
    await card('Пункт 2', 'Раздел «Услуги»', '«Фармацевтика» и «Лицензирование и аккредитация». Длинные названия видны полностью.');
    await point('Композитная', 'button.bn-sub');
    await say('Фармацевтика', 'Композитная услуга «Единого окна» и информация о предоставленных ЛС — названия переносятся целиком', 4400);
    await point('Информация о предоставленных', 'a.bn-sub');
    await say('Внешний переход', 'Услуга на eGov.kz отмечена значком ↗ и открывается в новой вкладке', 3800);
    await click('Лицензирование', 'button.bn-cat');
    await sleep(700);
    await say('Лицензирование и аккредитация', 'Десять услуг в порядке постановки', 3200);
    await point('Выдача сертификата специалиста', 'a.bn-sub');
    await say('Е-лицензирование', 'Первая услуга ведёт на «Е-лицензирование», остальные — на eGov.kz; у всех значок ↗', 4200);
    await page.evaluate(() => { const l = document.querySelector('.bn-list'); if(l) l.scrollTo({ top: l.scrollHeight, behavior: 'smooth' }); });
    await sleep(1400);
    await say('Длинные названия', 'Меню прокручивается, текст не обрезается и не выходит за пределы', 3400);
    await click('Лицензирование', 'button.bn-cat');
    await sleep(500);
    await page.evaluate(() => { const l = document.querySelector('.bn-list'); if(l) l.scrollTo({ top: 0, behavior: 'smooth' }); });
    await sleep(800);
  });

  // ── 3. Свёрнутое меню ─────────────────────────────────────────────
  await section('свёрнутое меню', async () => {
    await click('', 'button.bn-tg');
    await sleep(700);
    await say('Свёрнутое меню', 'Остаются иконки, подсказка с названием — при наведении', 3200);
    await click('', 'button[title="Услуги"]');
    await sleep(800);
    await say('Услуги из свёрнутого меню', 'Нажатие сразу разворачивает меню с открытым разделом', 3600);
  });

  // ── 4. Окно выбора направления ────────────────────────────────────
  await section('окно', async () => {
    await card('Пункт 2', 'Композитная услуга', 'Открывается окно с четырьмя направлениями: КНФ, Цены, ЕД, АЛО.');
    await click('Композитная', 'button.bn-sub');
    await waitText('Выберите направление');
    await sleep(700);
    await say('Выберите направление', 'Заголовок, четыре понятных варианта с расшифровкой и кнопка закрытия', 4000);
    await point('Цены', '.bn-dir');
    await say('Один клик', 'Выбор направления сразу открывает сценарий оформления заявки', 3400);
    await click('', '.bn-x');
    await sleep(600);
    await say('Закрытие', 'Крестик, Esc или клик по затемнению — окно закрывается без перехода', 3400);
    await click('Композитная', 'button.bn-sub');
    await waitText('Выберите направление');
    await sleep(500);
    await click('КНФ', '.bn-dir');
    await page.waitForFunction(() => decodeURIComponent(location.pathname).includes('Заявление КНФ'), { timeout: 20000 });
    await sleep(2200);
    await say('КНФ', 'Открылось заявление на экспертизу для включения в КНФ; в меню подсвечены «Услуги»', 4000);
  });

  // ── 5. Мои заявки: список ─────────────────────────────────────────
  await section('список', async () => {
    await card('Пункт 3', 'Страница «Мои заявки»', 'Единый список заявок КНФ, на цены, ЕД и АЛО.');
    await open('Мои заявки.dc.html');
    await sleep(200);
    await say('Загрузка данных', 'Пока данные загружаются — скелет таблицы', 1800);
    await waitText('Всего:', 15000);
    await sleep(600);
    await point('Всего:', 'div');
    await say('Количество', 'Сколько всего заявок — над таблицей', 3000);
    await point('Дата создания', '.sort');
    await say('По умолчанию', 'Сначала новые заявки — сортировка по дате создания', 3400);
    await point('Цены', '.c-svc');
    await say('Наименование услуги', 'Под названием — метка направления, тип продукции и торговое наименование', 4000);
    await point('—', '.c-date');
    await say('Дата подачи', 'Если заявка ещё не подана — «—»', 3000);
    await point('Черновик', '.c-st span');
    await say('Статус', 'Цветная метка с текстом', 2800);
  });

  // ── 6. Сортировка и страницы ──────────────────────────────────────
  await section('сортировка', async () => {
    await click('Статус', '.sort');
    await sleep(700);
    await say('Сортировка', 'По номеру, наименованию, датам и статусу; повторное нажатие меняет направление', 4000);
    await click('Статус', '.sort');
    await sleep(700);
    await click('Дата создания', '.sort');
    await sleep(700);
    await click('', '.pg[aria-label="Страница 2"]');
    await sleep(900);
    await say('Постраничный вывод', 'По 10 заявок на странице, сверху — диапазон и номера страниц', 3600);
    await click('', '.pg[aria-label="Страница 1"]');
    await sleep(700);
  });

  // ── 7. Фильтры ────────────────────────────────────────────────────
  await section('фильтры', async () => {
    await card('Пункт 3', 'Панель фильтров', 'Фильтры работают совместно и применяются кнопкой «Применить».');
    await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'smooth' }));
    await sleep(600);
    await click('', '#rq-sel-status');
    await sleep(600);
    await say('Статус заявки', 'Выпадающий список, по умолчанию «Все»', 2800);
    await click('В работе', '.opt');
    await sleep(400);
    await click('', '#rq-sel-service');
    await sleep(600);
    await say('Наименование услуги', 'Полные наименования с меткой направления', 3000);
    await click('лекарственного средства', '.opt');
    await sleep(400);
    await click('Применить', 'button.btn-p');
    await sleep(900);
    await say('Совместно', 'Статус «В работе» + услуга регистрации цены — «Найдено»', 3600);
    await click('Сбросить', 'button.btn-s');
    await sleep(900);
    await say('Сбросить', 'Очищает все условия сразу', 2800);
  });

  // ── 8. Период ─────────────────────────────────────────────────────
  await section('период', async () => {
    await card('Пункт 3–4', 'Период по дате создания', 'Если дата окончания раньше даты начала — сообщение об ошибке.');
    await type('#rq-from', '20102026', 110);
    await sleep(300);
    await type('#rq-to', '10102026', 110);
    await sleep(900);
    await say('Ошибка выбора периода', '«Дата окончания раньше даты начала», применить нельзя', 4000);
    await page.click('#rq-to', { clickCount: 3 });
    await page.keyboard.press('Backspace');
    await type('#rq-to', '31102026', 110);
    await sleep(500);
    await click('Применить', 'button.btn-p');
    await sleep(900);
    await say('Период', 'Заявки, созданные с 20 по 31 октября', 3000);
  });

  // ── 9. Поиск ──────────────────────────────────────────────────────
  await section('поиск', async () => {
    await click('Сбросить', 'button.btn-s');
    await sleep(500);
    await type('#rq-q', '4097', 140);
    await page.keyboard.press('Enter');
    await sleep(900);
    await say('Поиск заявки', 'По номеру заявки; Enter — как «Применить»', 3200);
    await click('', 'button[aria-label="Очистить поиск"]');
    await type('#rq-q', '999999', 120);
    await page.keyboard.press('Enter');
    await sleep(900);
    await say('Отсутствие результатов', '«Заявки не найдены» и кнопка «Сбросить фильтры»', 3600);
    await click('Сбросить фильтры', 'button.btn-s');
    await sleep(900);
  });

  // ── 10. Меню действий ─────────────────────────────────────────────
  await section('действия', async () => {
    await card('Пункт 3', 'Меню действий', 'Только доступные действия для статуса заявки.');
    await click('', 'button[aria-label="Действия с заявкой № 4097105"]');
    await sleep(800);
    await say('Черновик', '«Продолжить заполнение» и «Удалить» с подтверждением', 3600);
    await page.keyboard.press('Escape');
    await sleep(400);
    await click('', 'button[aria-label="Действия с заявкой № 4096862"]');
    await sleep(800);
    await say('Поданная заявка', '«Открыть карточку»; номер заявки в таблице — тоже ссылка на карточку', 3800);
    await page.keyboard.press('Escape');
    await sleep(500);
  });

  // ── 11. Состояния ─────────────────────────────────────────────────
  await section('состояния', async () => {
    await card('Пункт 4', 'Состояния интерфейса', 'Нет заявок, загрузка, ошибка загрузки с повтором.');
    await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'smooth' }));
    await sleep(500);
    await click('Нет заявок', '.demo-b');
    await sleep(900);
    await say('Заявок пока нет', 'Кнопка «Подать заявку» открывает то же окно выбора направления', 3600);
    await click('Подать заявку', 'button.btn-p');
    await waitText('Выберите направление');
    await sleep(900);
    await page.keyboard.press('Escape');
    await sleep(500);
    await click('Нет заявок', '.demo-b');
    await sleep(1400);
    await click('Ошибка загрузки', '.demo-b');
    await sleep(1400);
    await say('Ошибка загрузки', '«Не удалось загрузить заявки» и «Повторить попытку»', 3600);
    await click('Повторить попытку', 'button.btn-s');
    await sleep(300);
    await say('Повтор', 'Снова загрузка — и список на месте', 2200);
    await waitText('Всего:', 15000);
    await sleep(1200);
  });

  await card('Портал МЗ РК', 'Меню кабинета бизнеса и «Мои заявки»',
    'Меню по постановке, услуги по категориям, окно выбора направления и единый список заявок со всеми состояниями.', 5200);
}
