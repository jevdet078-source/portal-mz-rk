/**
 * Видео «АРМ ННЦРЗ и ФК — роли и процессы» (короткое, для аналитика).
 *
 *   npm run record -- ed-arm-roles   → exports/video/15. АРМ ННЦРЗ и ФК — роли и процессы.mp4
 *
 * Показывает, какие роли есть в АРМ ННЦРЗ и АРМ Формулярной комиссии, как переключаться
 * «Работать от имени» и что видит каждая роль: очередь задач, форму решения эксперта,
 * согласование руководства с маршрутом, подпись ПП, хронологию; в ФК — секретаря,
 * участника с голосованием и председательствующего с подписью протокола.
 * Подробный проход по действиям — сценарий ed-arm.
 */

export const title = 'АРМ ННЦРЗ и ФК — роли и процессы';
export const fileName = '15. АРМ ННЦРЗ и ФК — роли и процессы';
export const start = 'АРМ ННЦРЗ.dc.html';

export default async function record(ctx) {
  const { page, sleep, say, title: card, click, point, open, section } = ctx;

  // «Работать от имени» в шапке АРМ
  const actAs = async (name) => {
    await click('', 'button[title="Сотрудник и роль"]');
    await sleep(500);
    await click(name, '[role="menuitemradio"]');
    await sleep(1200);
  };

  await card('Портал МЗ РК · услуга ЕД', 'АРМ ННЦРЗ и Формулярной комиссии — роли',
    'Какие роли есть в каждом АРМ, как переключаться между ними и какие процессы у каждой роли.', 5000);

  await section('роли', async () => {
    await open('АРМ ННЦРЗ.dc.html');
    await click('', 'button[title="Сотрудник и роль"]');
    await sleep(700);
    await say('Работать от имени', 'В шапке АРМ — все сотрудники: ННЦРЗ (эксперты, проф. эксперты, начальник управления, директор департамента, ЗПП, ПП) и Формулярной комиссии', 5600);
    await point('Задачи', '[role="menu"] span');
    await say('Задачи роли', 'Справа — сколько задач ждёт каждого сотрудника. Выбор сотрудника сразу меняет очередь и доступные действия', 4600);
    await click('', 'button[title="Сотрудник и роль"]');   // повторное нажатие закрывает меню
    await sleep(500);
  });

  await section('начальник управления', async () => {
    await point('Мои задачи', '[role="tab"]');
    await say('Начальник управления', '«Мои задачи» — заявки, где «Назначено на» — он: новые на назначение и решения на согласование', 4600);
    await click('Все заявки', '[role="tab"]');
    await sleep(800);
    await say('Все заявки', 'Выбранная вкладка выделена. Фильтры — в одну линию, статусы — компактными метками', 4200);
    await open('Карточка заявки ННЦРЗ.dc.html?n=0000150');
    await say('Согласование', 'У руководителя — «Согласовать» и «На доработку». Ниже решение эксперта и маршрут согласования по шагам', 4800);
    await point('Ожидает согласования', 'li');
    await sleep(1200);
  });

  await section('эксперт', async () => {
    await actAs('Сагинов');
    await open('АРМ ННЦРЗ.dc.html');
    await say('Эксперт', 'Своя очередь: решение по пункту 7, подтверждение оплаты, первичная экспертиза, доработка', 4400);
    await open('Карточка заявки ННЦРЗ.dc.html?n=0000151');
    await click('Не соответствует пункту 7', '[role="radio"]');
    await say('Решение эксперта', 'Форма текущего шага: решение, обязательный счёт 20 %. Кнопка включится, когда всё заполнено — подсказка слева', 5000);
  });

  await section('проф. экспертиза и замечания', async () => {
    await actAs('Жумабекова');
    await open('Карточка заявки ННЦРЗ.dc.html?n=0000154');
    await click('Заявление', 'nav[aria-label="Разделы заявки"] button');
    await sleep(700);
    await say('Замечания к полям', 'Назначенный эксперт оставляет замечание к любому полю заявления — иконка справа от подписи', 4600);
  });

  await section('председатель правления', async () => {
    await actAs('Ахметов');
    await open('Карточка заявки ННЦРЗ.dc.html?n=0000160');
    await say('Председатель Правления', 'Подписывает итоговые документы. Завершённые шаги свёрнуты, открыт блок, который ждёт подписи', 4600);
    await point('Ожидает подписи', 'li');
    await say('Маршрут', 'Эксперт → начальник управления → директор департамента → ПП: кто, когда и что сделал', 4200);
    await point('Профессиональная экспертиза', '[role="tab"]');
    await say('Документы по этапам', 'Активный этап выделен цветом и подчёркиванием, у каждого — счётчик документов', 3800);
    await click('Хронология заявки', 'button');
    await sleep(900);
    await say('Хронология', 'Каждое действие всех ролей — строкой: роль, ФИО, даты, статус, комментарий', 4200);
    await page.keyboard.press('Escape');
    await sleep(400);
  });

  await section('секретарь ФК', async () => {
    await actAs('Абдрахманова');
    await sleep(800);
    await say('АРМ Формулярной комиссии', 'Выбор сотрудника ФК открывает АРМ ФК. Секретарь видит все комиссии и создаёт новые', 4600);
    await point('Участники', '[role="columnheader"]');
    await say('Комиссии', 'Участники — кружки с первыми цифрами ИИН, зелёное кольцо — проголосовал; статус и таймер этапа', 4600);
    await open('Комиссия ФК.dc.html?id=c7&from=active');
    await say('Решение секретаря', 'После голосования секретарь видит явку и голоса и фиксирует, состоялась ли комиссия', 4400);
  });

  await section('участник ФК', async () => {
    await actAs('Ким');
    await open('Комиссия ФК.dc.html?id=c6&from=active');
    await say('Член комиссии', 'Участник видит только свои комиссии и голосует «За» / «Против» по каждому ЛС / МИ, затем подписывает голос ЭЦП', 4800);
  });

  await section('председательствующий ФК', async () => {
    await actAs('Ибраев');
    await open('Комиссия ФК.dc.html?id=c8&from=approval');
    await say('Председательствующий', 'Раздел «Согласование» и кнопка «Подписать» — после подписи формируются именной и обезличенный протоколы', 4800);
  });

  await card('Портал МЗ РК · услуга ЕД', 'Роли АРМ ННЦРЗ и ФК',
    'Переключение «Работать от имени» в шапке: у каждой роли — своя очередь задач и свои действия по постановкам UC01.13.3 и UC01.13.4.', 5200);
}
