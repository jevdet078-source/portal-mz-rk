/**
 * Видео «Авторизация пользователей» — по постановке аналитика.
 *
 *   npm run record -- auth   → exports/video/1. Авторизация.mp4
 *
 * Ветки: несколько профилей и неверный пароль; один профиль и вход из услуги;
 * пользователь не зарегистрирован; учётная запись INACTIVE; невалидная ЭЦП.
 */

export const title = 'Авторизация';
export const fileName = '1. Авторизация';
export const start = 'Вход.dc.html';

export default async function record(ctx) {
  const { sleep, caption, say, title: card, click, point, locate, type, clearField, waitText, open, section } = ctx;

  /** Выбрать тестовый сертификат в окне ЭЦП (группа ошибок раскрывается при необходимости). */
  async function pick(match) {
    await waitText('Выберите сертификат ЭЦП');
    await caption('Выбор ключа ЭЦП', 'В рабочей версии — окно NCALayer, в прототипе — тестовый сертификат для этого сценария');
    await sleep(700);
    if (!(await locate(match, '.ecp-item'))) {
      await click('Показать', 'button');
      await sleep(400);
    }
    await click(match, '.ecp-item');
    await caption('Проверка ЭЦП', 'Проверяется сертификат, затем — запросы во внешние системы');
  }
  /** Открыть окно ЭЦП с того экрана, где мы сейчас. */
  async function openEcp() {
    for (const label of ['Выбрать другой ключ', 'Повторить', 'Войти с ЭЦП']) {
      if (await locate(label, 'button')) { await click(label, 'button'); return; }
    }
    throw new Error('нет кнопки выбора ключа');
  }

  await card('Портал МЗ РК · прототип', 'Авторизация пользователей',
    'ЭЦП → проверка сертификата → учётная запись → профиль → пароль. Логин определяется автоматически по ИИН из ЭЦП.', 5200);

  // ── 1. Несколько профилей, неверный пароль ─────────────────────────
  await section('несколько профилей', async () => {
    await card('Сценарий 1', 'Личная ЭЦП ФЛ, несколько профилей', 'Пользователь зарегистрирован как гражданин и как ИП — выбирает, под каким профилем войти.');
    await say('Шаг 1 · ЭЦП', 'Вход начинается с ЭЦП. ИИН и логин вводить не нужно — система получит их из сертификата');
    await point('Войти с ЭЦП', 'button');
    await click('Войти с ЭЦП', 'button');
    await say('Выбор ключа', 'В рабочей версии здесь откроется окно NCALayer. В прототипе — тестовые сертификаты под каждую ветку постановки', 3600);
    await pick('ИИН 920315401540');
    await caption('Валидация ЭЦП', 'Проверяются подпись, срок действия и статус сертификата, определяются ИИН и тип ЭЦП, ищется учётная запись');
    await waitText('Выберите профиль');
    await sleep(1500);
    await say('Шаг 2 · Профиль', 'Личная ЭЦП ФЛ: профили «Гражданин» и «Бизнес» (ИП). Показываются только профили, уже зарегистрированные на этот ИИН');
    await point('Добавить профиль', 'a');
    await say('Нет нужного профиля?', '«Добавить профиль» ведёт в регистрацию с тем же ключом — выбирать ЭЦП повторно не нужно');
    await click('Гражданин', 'button.opt');
    await say('Шаг 3 · Пароль', 'Логин подставлен из ИИН в ЭЦП и не редактируется. Остаётся ввести пароль');
    await type('#login-pass', 'qwerty123');
    await click('Войти', 'button[type=submit]');
    await waitText('Неверный пароль.');
    await say('Ошибка пароля', 'Текст по постановке — «Неверный пароль.» Поле подсвечено, ввод выделен: можно сразу набрать заново', 4200);
    await clearField('#login-pass');
    await type('#login-pass', 'Demo#2026');
    await click('', 'button.eye');
    await say('Показать пароль', 'Кнопка «глаз» показывает введённый пароль — меньше ошибок при наборе', 2600);
    await caption('Вход', 'Пароль верный — открывается кабинет выбранного профиля');
    await click('Войти', 'button[type=submit]');
    await sleep(2800);
    await say('Вход выполнен', 'Профиль «Гражданин» → личный кабинет. Сохранены ИИН и выбранный профиль', 3400);
  });

  // ── 2. Один профиль, вход из услуги ─────────────────────────────────
  await section('один профиль', async () => {
    await open('Вход.dc.html?profile=business&return=' + encodeURIComponent('Паспорт услуги.dc.html?start=1#price-ls'), { reset: true });
    await card('Сценарий 2', 'ЭЦП юрлица с одним профилем', 'Вход из услуги «Регистрация цены ЛС»: шаг выбора профиля пропускается, после входа — возврат к услуге.');
    await point('Вход для подачи заявки', 'div[role=note]');
    await say('Вход из услуги', 'Пользователь нажал «Получить услугу» без входа. Подсказка объясняет, что нужен профиль «Бизнес»');
    await click('Войти с ЭЦП', 'button');
    await pick('Астана Групп');
    await caption('ЭЦП ЮЛ', 'Из сертификата определяются ИИН сотрудника и БИН организации');
    await waitText('Введите пароль');
    await sleep(1200);
    await say('Один профиль — без лишнего шага', 'На этот БИН зарегистрирован только «Бизнес», поэтому экран выбора пропущен и сразу открыт ввод пароля', 4200);
    await type('#login-pass', 'Demo#2026');
    await caption('Вход', 'Пароль верный — возвращаем пользователя к услуге');
    await click('Войти', 'button[type=submit]');
    await sleep(3200);
    await say('Возврат к услуге', 'После входа пользователь вернулся к услуге и продолжил подачу заявки', 3600);
  });

  // ── 3. Не зарегистрирован ──────────────────────────────────────────
  await section('не зарегистрирован', async () => {
    await open('Вход.dc.html', { reset: true });
    await card('Сценарий 3', 'Пользователь не зарегистрирован', 'ЭЦП валидна, но учётной записи с этим ИИН в системе нет.');
    await click('Войти с ЭЦП', 'button');
    await pick('Касымов');
    await waitText('Вы ещё не зарегистрированы');
    await sleep(800);
    await say('Нет учётной записи', 'Текст по постановке: «Пользователь не зарегистрирован в системе. Для продолжения необходимо пройти регистрацию.»', 4600);
    await point('Зарегистрироваться', 'button');
    await say('Переход в регистрацию', 'Кнопка открывает регистрацию и передаёт туда ключ ЭЦП — выбирать его заново не нужно');
    await click('Зарегистрироваться', 'button');
    await waitText('Выберите профиль', 15000);
    await sleep(1000);
    await say('Регистрация продолжена с тем же ключом', 'Проверки пройдены автоматически. Сама регистрация — в отдельном видео', 3800);
  });

  // ── 4. INACTIVE ───────────────────────────────────────────────────
  await section('inactive', async () => {
    await open('Вход.dc.html', { reset: true });
    await card('Сценарий 4', 'Учётная запись недоступна', 'Пользователь найден, но его статус — INACTIVE.');
    await click('Войти с ЭЦП', 'button');
    await pick('Учётка заблокирована');
    await waitText('Учетная запись недоступна');
    await sleep(800);
    await say('Вход невозможен', 'Статус INACTIVE — дальше не пускаем. Текст по постановке: «Учетная запись недоступна. Обратитесь к администратору системы.»', 5000);
  });

  // ── 5. Невалидная ЭЦП ─────────────────────────────────────────────
  await section('невалидная ЭЦП', async () => {
    await card('Сценарий 5', 'Невалидная ЭЦП', 'При неуспешной валидации дальнейшее прохождение авторизации не разрешается.');
    const cases = [
      ['Срок истёк', 'Срок действия сертификата истёк', 'Проверка срока не пройдена: показываем дату окончания и что делать дальше'],
      ['Отозван', 'Сертификат отозван', 'Проверка статуса не пройдена — нужен действующий ключ'],
      ['Ключ подписи', 'Выбран ключ для подписания документов', 'Для входа нужен ключ аутентификации — подсказываем, как его отличить'],
      ['NCALayer не запущен', 'NCALayer не запущен', 'Подпись не получена: предлагаем запустить NCALayer и повторить или скачать его'],
    ];
    for (const [cert, head, text] of cases) {
      await openEcp();
      await pick(cert);
      await waitText(head);
      await sleep(900);
      await say(head, text, 3800);
    }
  });

  await card('Итого', 'Авторизация', 'ЭЦП → валидация сертификата → учётная запись (нет / INACTIVE) → профиль (один — выбирается сам) → пароль. Регистрация — в следующих видео.', 5600);
}
