/**
 * Видео «Кабинет бизнеса — оплата госпошлины: ПШЭП и Halyk Bank» (для аналитика).
 *
 *   npm run record -- fee-payment   → exports/video/17. Кабинет бизнеса — оплата госпошлины, ПШЭП и Halyk Bank.mp4
 *
 * Этап 2 «Оплата государственной пошлины» по доработке UC11.03: реквизиты и «Скачать реквизиты»
 * убраны, добавлены выбор способа оплаты (ПШЭП или Halyk Bank), сумма к оплате с комиссией,
 * иконки на кнопках убраны. Проходит все 10 состояний блока оплаты из раздела 6, нехватку МРП
 * в справочнике, доверенность, отправку и итоговый вид этапа.
 *
 * Ответ банка и уведомление об оплате в прототипе эмулирует панель «Платёж»; в записи она
 * скрыта (её закрывал бы субтитр) и переключается скриптом — субтитр говорит, что произошло.
 */

export const title = 'Кабинет бизнеса — оплата госпошлины: ПШЭП и Halyk Bank';
export const fileName = '17. Кабинет бизнеса — оплата госпошлины, ПШЭП и Halyk Bank';
export const start = 'Процесс.dc.html';

export default async function record(ctx) {
  const { page, sleep, say, caption, title: card, click, point, show, waitText, open, section } = ctx;

  // переключатель панели прототипа: событие на стороне банка или настройка демо
  const sim = async (label, nth = 0) => {
    await page.evaluate(([t, n]) => {
      const all = [...document.querySelectorAll('[data-proto-panel] button')].filter((b) => b.textContent.trim() === t);
      all[n].click();
    }, [label, nth]);
    await sleep(500);
  };
  const hidePanel = () => page.evaluate(() => {
    const st = document.createElement('style');
    st.textContent = '[data-proto-panel]{display:none !important}';
    document.head.appendChild(st);
  });
  const stage2 = async () => {
    await page.evaluate(() => {
      const el = document.getElementById('stage-2');
      window.scrollTo({ top: el.getBoundingClientRect().top + scrollY - 88, behavior: 'smooth' });
    });
    await sleep(900);
  };

  await card('Портал МЗ РК · кабинет бизнеса', 'Оплата государственной пошлины',
    'Доработка этапа 2 по UC11.03: вид пошлины, способ оплаты — ПШЭП или Halyk Bank, сумма к оплате и статус платежа.', 6000);

  await section('экран этапа', async () => {
    await page.evaluate(() => localStorage.setItem('mp-proc-ls', 'p2'));
    await open('Процесс.dc.html#ls');
    await hidePanel();
    await stage2();
    await say('Было → стало', 'Блок реквизитов и «Скачать реквизиты» убраны — ЕО передаёт реквизиты в банк сам. Иконок на кнопках больше нет', 5800);
    await point('Выберите вид пошлины', '#fee-label');
    await say('1 · Вид не выбран', 'Три варианта: на регистрацию — 11 МРП, на перерегистрацию — 5 МРП, внесение изменений — бесплатно. Обе кнопки неактивны', 6000);
  });

  await section('вид и способ оплаты', async () => {
    await click('На регистрацию', '[role="radio"]');
    await say('2 · Вид выбран', 'Появился выбор способа оплаты. Комиссия видна сразу на карточке — сравнивать можно до выбора', 5600);
    await click('ПШЭП', '[role="radio"]');
    await say('10 · Вид и способ выбраны', 'Сумма к оплате: 11 МРП × 4 325 ₸ = 47 575 ₸, без комиссии. «Перейти к оплате» активна', 5600);
    await click('Halyk Bank', '[role="radio"]');
    await say('Смена способа', 'Halyk Bank — комиссия 4%: 49 478 ₸, из них 1 903 ₸ комиссия. Сумма пересчитывается сразу', 5600);
    await click('На перерегистрацию', '[role="radio"]');
    await say('Смена вида', 'Перерегистрация — 5 МРП: 22 490 ₸ с комиссией Halyk Bank. Расчёт на стороне ЕО', 5000);
    await click('На регистрацию', '[role="radio"]');
    await click('ПШЭП', '[role="radio"]');
  });

  await section('создание платежа', async () => {
    await caption('3 · Создан', 'ЕО создаёт платёж и запрашивает ссылку в банке — индикатор на кнопке, все кнопки неактивны');
    await click('Перейти к оплате', 'button');
    await sleep(1200);
    await sim('Создан');            // задерживаем состояние «Создан», чтобы его было видно
    await sleep(2600);
    await sim('Ожидает');
    await say('4 · Ожидает оплаты', 'Страница банка открывается в новой вкладке. Вид и способ заблокированы, повторное нажатие откроет ту же ссылку', 6200);
  });

  await section('уведомление банка', async () => {
    await sim('Удержан');
    await say('5 · Удержан', '«Платеж обрабатывается, дождитесь подтверждения». Обе кнопки неактивны', 4800);
    await sim('Оплачен');
    await say('6 · Оплачен', 'Статус обновился сам по уведомлению банка — кнопки «Обновить» нет. Ссылка «Электронный чек»', 5600);
    await point('Отправить', 'button');
    await say('«Отправить» активна', 'Пошлина оплачена, доверенность не требуется — этап можно отправить', 4200);
  });

  await section('ошибки', async () => {
    await sim('Ошибка');
    await stage2();
    await say('7 · Ошибка инициализации', 'Банк не вернул ссылку. Вид и способ снова можно сменить, «Перейти к оплате» создаст новый платёж', 5800);
    await sim('Проверка');
    await say('8 · Требует проверки', 'Сумма в уведомлении банка не совпала с записью платежа. Выбор заблокирован, обе кнопки неактивны', 5600);
    await sim('Не создан');
    await sim('Нет');
    await say('Нет МРП на текущий год', 'Сумму не рассчитать — платёж не создаётся, «Перейти к оплате» неактивна', 5200);
    await sim('Есть');
  });

  await section('внесение изменений', async () => {
    await click('Внесение изменений', '[role="radio"]');
    await say('9 · Внесение изменений', 'Способа оплаты, суммы и кнопки оплаты нет: «Оплата государственной пошлины не требуется». «Отправить» активна сразу', 6000);
  });

  await section('доверенность', async () => {
    await sim('Нужна');
    await show('Загрузите доверенность', 'div');
    await say('Доверенность', 'Если она требуется — поле обязательное, и «Отправить» ждёт загрузки файла', 4600);
    await click('На регистрацию', '[role="radio"]');
    await click('ПШЭП', '[role="radio"]');
    await sim('Оплачен');
    await click('Выберите файл', 'div[style*="dashed"]');
    await sleep(600);
    await click('Отправить', 'button');
    await waitText('Подтвердить', 4000);
    await say('Подтверждение', 'Короткое предупреждение перед отправкой', 3800);
    await click('Подтвердить', 'button');
    await stage2();
    await say('Отправлено', 'Вместо формы — сводка: вид пошлины, способ оплаты, сумма и электронный чек', 5200);
  });

  await section('этап завершён', async () => {
    await sim('Завершён');
    await click('Оплата государственной пошлины', '#stage-2 > button');
    await sleep(600);
    await stage2();
    await say('Итог этапа', 'Та же сводка остаётся на этапе для справки', 4400);
  });

  await card('Портал МЗ РК · кабинет бизнеса', 'Оплата госпошлины: ПШЭП и Halyk Bank',
    'Все 10 состояний блока оплаты UC11.03. Вопросы к аналитику — в docs/06-backlog.md.', 5200);
}
