/**
 * Видео «Кабинет бизнеса — оплата госпошлины через ПШЭП» (для аналитика).
 *
 *   npm run record -- fee-payment   → exports/video/16. Кабинет бизнеса — оплата госпошлины через ПШЭП.mp4
 *
 * Этап 2 «Оплата государственной пошлины» по UC11.03: вместо загрузки чека — выбор вида
 * пошлины и переход на оплату в ПШЭП (UC9.16), статус платежа обновляется по callback
 * (UC9.15). Проходит все 9 состояний блока оплаты из раздела 6, доверенность, отправку
 * и итоговый вид этапа.
 *
 * Ответ ПШЭП и уведомление об оплате в прототипе эмулирует панель «Платёж»; в записи она
 * скрыта (её закрывал бы субтитр) и переключается скриптом — субтитр говорит, что произошло.
 */

export const title = 'Кабинет бизнеса — оплата госпошлины через ПШЭП';
export const fileName = '16. Кабинет бизнеса — оплата госпошлины через ПШЭП';
export const start = 'Процесс.dc.html';

export default async function record(ctx) {
  const { page, sleep, say, caption, title: card, click, point, show, waitText, open, section } = ctx;

  // переключатель панели прототипа: событие на стороне ПШЭП или настройка демо
  const sim = async (label, nth = 0) => {
    await page.evaluate(([t, n]) => {
      const all = [...document.querySelectorAll('[data-proto-panel] button')].filter((b) => b.textContent.trim() === t);
      all[n].click();
    }, [label, nth]);
    await sleep(500);
  };
  const hidePanel = () => page.evaluate(() => {
    const st = document.createElement('style');
    st.textContent = '[data-proto-panel]{display:none !important}';
    document.head.appendChild(st);
  });
  const stage2 = async () => {
    await page.evaluate(() => {
      const el = document.getElementById('stage-2');
      window.scrollTo({ top: el.getBoundingClientRect().top + scrollY - 88, behavior: 'smooth' });
    });
    await sleep(900);
  };

  await card('Портал МЗ РК · кабинет бизнеса', 'Оплата государственной пошлины через ПШЭП',
    'Этап 2 сквозного процесса ЛС / МИ по UC11.03: вместо загрузки чека — выбор вида пошлины и оплата в Платёжном шлюзе «электронного правительства».', 6000);

  await section('экран этапа', async () => {
    await page.evaluate(() => localStorage.setItem('mp-proc-ls', 'p2'));
    await open('Процесс.dc.html#ls');
    await hidePanel();
    await stage2();
    await say('Было → стало', 'Поле загрузки чека и кнопка «Загрузить» убраны. В шапке блока — «Выберите вид пошлины и перейдите к оплате», реквизиты прежние', 5600);
    await point('Выберите вид пошлины', '#fee-label');
    await say('1 · Вид не выбран', 'Три варианта: на регистрацию — 11 МРП, на перерегистрацию — 5 МРП, внесение изменений — бесплатно. «Перейти к оплате» и «Отправить» неактивны', 6200);
  });

  await section('выбор и переход к оплате', async () => {
    await click('На регистрацию', '[role="radio"]');
    await say('2 · Вид выбран', '«Перейти к оплате» активна, «Отправить» — пока нет. Сумма на этапе не показывается: её считает ЕО (МРП года × 11) и показывает ПШЭП', 6000);
    await caption('3 · Создан', 'ЕО создаёт платёж и запрашивает ссылку в ПШЭП — индикатор на кнопке, все кнопки неактивны');
    await click('Перейти к оплате', 'button');
    await sleep(1200);
    await sim('Создан');            // задерживаем состояние «Создан», чтобы его было видно
    await sleep(2600);
    await sim('Ожидает');
    await say('4 · Ожидает оплаты', 'Страница ПШЭП открывается в новой вкладке. Статус — рядом с кнопкой. Вид пошлины заблокирован, повторное нажатие откроет ту же ссылку', 6200);
  });

  await section('callback ПШЭП', async () => {
    await sim('Удержан');
    await say('5 · Удержан', 'ПШЭП прислал Hold: «Платеж обрабатывается, дождитесь подтверждения». Обе кнопки неактивны', 5000);
    await sim('Оплачен');
    await say('6 · Оплачен', 'Уведомление Paid (UC9.15) — статус обновился сам, кнопки «Обновить» нет. Дата оплаты и ссылка «Электронный чек»', 5600);
    await point('Отправить', 'button');
    await say('«Отправить» активна', 'Пошлина оплачена, доверенность не требуется — этап можно отправить', 4200);
  });

  await section('ошибки', async () => {
    await sim('Ошибка');
    await stage2();
    await say('7 · Ошибка инициализации', 'ПШЭП не вернул ссылку или ответ не получен. Вид пошлины можно сменить, «Перейти к оплате» создаст новый платёж', 5800);
    await sim('Проверка');
    await say('8 · Требует проверки', 'Сумма или номер платежа в уведомлении не совпали с ЕО. Обе кнопки неактивны — обратиться в поддержку', 5600);
  });

  await section('внесение изменений', async () => {
    await sim('Не создан');
    await click('Внесение изменений', '[role="radio"]');
    await say('9 · Внесение изменений', 'Платёж не создаётся, кнопки оплаты нет: «Оплата государственной пошлины не требуется». «Отправить» активна сразу', 5800);
  });

  await section('доверенность', async () => {
    await sim('Нужна');
    await show('Загрузите доверенность', 'div');
    await say('Доверенность', 'Если она требуется — поле обязательное, и «Отправить» ждёт загрузки файла', 4600);
    await click('Выберите файл', 'div[style*="dashed"]');
    await sleep(600);
    await click('Отправить', 'button');
    await waitText('Подтвердить', 4000);
    await say('Подтверждение', 'Перед отправкой — короткое предупреждение: после отправки вид пошлины и доверенность изменить нельзя', 5000);
    await click('Подтвердить', 'button');
    await stage2();
    await say('Отправлено', 'Выбранный вид и статус оплаты остаются на этапе для справки, этап 3 запустится автоматически', 5000);
  });

  await section('этап завершён', async () => {
    await sim('Завершён');
    await click('Оплата государственной пошлины', '#stage-2 > button');
    await sleep(600);
    await stage2();
    await say('Итог этапа', '«Вид пошлины», «Пошлина оплачена», дата и электронный чек ПШЭП вместо загруженного файла', 5000);
  });

  await card('Портал МЗ РК · кабинет бизнеса', 'Оплата госпошлины через ПШЭП',
    'Все 9 состояний блока оплаты UC11.03. Вопросы к аналитику — в docs/06-backlog.md.', 5200);
}
