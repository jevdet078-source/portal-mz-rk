/**
 * Видео «Государственные услуги — замечания 14.10» — правки по документам аналитика
 * «замечания 14.10.docx» и «Дополнительные замечания и комментарии.docx».
 *
 *   npm run record -- gov-services-final   → exports/video/13. Государственные услуги — замечания 14.10.mp4
 *
 * «Гражданам»: «Медорганизации» без блока «Медицинские услуги», «ОСМС и отчисления» убран.
 * «Бизнесу»: только плитка «Государственные услуги»; в «Фармацевтике» композитная услуга
 * «Единого окна» → вход → сразу «Услуги» кабинета бизнеса; повторно — без входа.
 * Кабинет бизнеса без онбординга. «Медперсоналу» — без госуслуг.
 */

export const title = 'Государственные услуги — замечания 14.10';
export const fileName = '13. Государственные услуги — замечания 14.10';
export const start = 'Портал Минздрава - Главная.dc.html';

export default async function record(ctx) {
  const { page, sleep, caption, say, title: card, click, point, locate, type, waitText, open, section, at } = ctx;

  // Шапка и баннер закреплены — берём координаты как есть, без прокрутки к элементу
  async function hdr(selector, press, text) {
    const box = await page.evaluate((sel, txt) => {
      const el = [...document.querySelectorAll(sel)].find(e => !txt || e.textContent.includes(txt));
      if (!el) return null; const r = el.getBoundingClientRect();
      return { x: Math.round(r.left + r.width / 2), y: Math.round(r.top + r.height / 2) };
    }, selector, text || '');
    if (!box) throw new Error('нет на экране: ' + selector + ' ' + (text || ''));
    await at(box.x, box.y);
    await sleep(600);
    if (!press) return;
    await page.evaluate(() => { const r = document.getElementById('demo-ring'); r.classList.remove('on'); void r.offsetWidth; r.classList.add('on'); });
    await sleep(200);
    await page.mouse.click(box.x, box.y);
    await sleep(600);
  }
  const role = (label) => `.hdr-roles button:nth-child(${['Гражданам', 'Бизнесу', 'Медперсоналу'].indexOf(label) + 1})`;

  await card('Портал МЗ РК · замечания аналитика 14.10', 'Государственные услуги — финальные правки',
    'Состав разделов по ролям, композитная услуга «Единого окна» со входом и прямым переходом, кабинет бизнеса без онбординга.', 5600);

  // ── Гражданам ────────────────────────────────────────────────────
  await section('гражданам', async () => {
    await open('Портал Минздрава - Главная.dc.html', { reset: true });
    await waitText('Новое на портале', 15000);
    await card('Гражданам', '«Медорганизации» и без «ОСМС и отчислений»', 'Запись, вызов врача и прикрепление — это госуслуги: они в «Государственных услугах».');
    await hdr(role('Гражданам'), true);
    await hdr('button.mp-tile', true, 'Медорганизации');
    await sleep(500);
    await say('Медорганизации', 'Раздел переименован. Блок «Медицинские услуги» удалён — остались организации и врачи', 4000);
    await hdr('button.mp-tile', true, 'Медорганизации');
    await say('ОСМС и отчисления', 'Плитка удалена полностью вместе с меню; сведения об ОСМС — госуслуга «Информация об ОСМС»', 4200);
  });

  // ── Бизнесу: главная ─────────────────────────────────────────────
  await section('бизнесу', async () => {
    await card('Бизнесу', 'Только «Государственные услуги»', 'Плитки «Фармацевтика», «Сан-эпид надзор» и «Аккредитация и лицензирование» удалены.');
    await hdr(role('Бизнесу'), true);
    await sleep(500);
    await say('Бизнесу', 'В верхнем блоке одна плитка — «Государственные услуги». Фармацевтика и лицензирование — категории внутри неё', 4400);
    await hdr('a.mp-tile', true);
    await waitText('Для бизнеса', 15000);
    await sleep(700);
  });

  // ── Фармацевтика: композитная услуга ─────────────────────────────
  await section('фармацевтика', async () => {
    await card('Замечание 1', 'Композитная услуга вместо двух', '«Получение заключения о безопасности…» и «Регистрация цены…» заменены одной услугой «Единого окна».');
    await click('Фармацевтика', 'button.gs-cat');
    await sleep(500);
    await point('Композитная', 'a.gs-row');
    await say('Новая услуга', 'Композитная госуслуга по регистрации ЛС и МИ по принципу «Единого окна». Две прежние услуги убраны', 4400);
    await point('Вход с ЭЦП', '.gs-meta');
    await say('Подсказка', 'Услуга оформляется на портале: значок → и метка «Вход с ЭЦП · профиль «Бизнес»» — в отличие от внешних ссылок eGov.kz', 4600);
    await click('Композитная', 'a.gs-row');
    await waitText('Вход для подачи заявки', 15000);
    await sleep(600);
  });

  // ── Вход и автоматический переход ────────────────────────────────
  await section('вход', async () => {
    await say('Неавторизованный пользователь', 'Нажатие на услугу ведёт на страницу входа. Подсказка: нужен профиль «Бизнес»', 3800);
    await point('Вернуться к перечню', 'a');
    await say('Передумали?', '«Вернуться к перечню услуг» — обратно в «Фармацевтику», без входа', 3200);
    await click('Войти с ЭЦП', 'button');
    await waitText('Выберите сертификат ЭЦП');
    await caption('Выбор ключа ЭЦП', 'В прототипе — тестовый сертификат организации');
    await sleep(700);
    await click('Астана Групп', '.ecp-item');
    await waitText('Введите пароль', 15000);
    await sleep(800);
    await type('#login-pass', 'Demo#2026');
    await caption('Вход', 'Профиль «Бизнес» — после входа сразу открывается услуга');
    await click('Войти', 'button[type=submit]');
    await waitText('Лекарственные средства', 15000);
    await sleep(1200);
    await say('Интерфейс услуги', 'Сразу «Услуги» кабинета бизнеса — искать и выбирать услугу повторно не нужно', 4400);
  });

  // ── Кабинет без онбординга ───────────────────────────────────────
  await section('кабинет', async () => {
    await card('Кабинет бизнеса', 'Без блока онбординга', 'Все разделы доступны сразу — меню не скрывает пункты до прохождения шагов.');
    await click('Главная', 'nav a');
    await waitText('Здравствуйте', 15000);
    await sleep(800);
    await say('Главная кабинета', 'Блок «Онбординг завершен» и шаги удалены. Остались приветствие и «Помощь»', 4000);
  });

  // ── Уже авторизован ──────────────────────────────────────────────
  await section('повторно', async () => {
    await open('Государственные услуги.dc.html?for=business&cat=pharma');
    await waitText('Для бизнеса', 15000);
    await sleep(600);
    await point('В кабинете бизнеса', '.gs-meta');
    await say('Уже вошли под «Бизнесом»', 'Метка меняется на «В кабинете бизнеса» — переход в услугу без входа', 3800);
    await click('Композитная', 'a.gs-row');
    await waitText('Лекарственные средства', 15000);
    await sleep(1000);
    await say('Прямой переход', 'Сразу интерфейс услуги', 2600);
  });

  // ── Медперсоналу ─────────────────────────────────────────────────
  await section('медперсоналу', async () => {
    await open('Портал Минздрава - Главная.dc.html');
    await waitText('Новое на портале', 15000);
    await card('Замечание 2', 'Медперсоналу — без госуслуг', 'Плитка, страница и переходы в «Государственные услуги» у медперсонала исключены.');
    await hdr(role('Медперсоналу'), true);
    await sleep(600);
    await say('Медперсоналу', 'Профессиональная деятельность, клинические протоколы, документация — плитки «Государственные услуги» нет', 4400);
    await open('Государственные услуги.dc.html?for=medical');
    await waitText('Новое на портале', 15000);
    await sleep(800);
    await say('Старые ссылки', 'Адрес госуслуг для медперсонала ведёт на главную — страницы перечня у этой роли нет', 4000);
  });

  await card('Портал МЗ РК', 'Государственные услуги — замечания 14.10', 'Учтены оба документа аналитика: роли «Гражданам», «Бизнесу», «Медперсоналу», композитная услуга со входом и кабинет бизнеса.', 4800);
}
