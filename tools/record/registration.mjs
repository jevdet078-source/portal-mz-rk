/**
 * Видео «Регистрация — основные сценарии» — по постановке аналитика.
 *
 *   npm run record -- registration   → exports/video/2. Регистрация — основные сценарии.mp4
 *
 * Ветки: ЭЦП ФЛ с ИП (полный проход и вход), ЭЦП ФЛ без ИП, ЭЦП ЮЛ медорганизации (СУР),
 * госорган (справочник organization_go), ЮЛ без права подписи, добавление профиля
 * существующему пользователю, пользователь уже зарегистрирован.
 */

export const title = 'Регистрация — основные сценарии';
export const fileName = '2. Регистрация — основные сценарии';
export const start = 'Регистрация.dc.html';

export default async function record(ctx) {
  const { sleep, caption, say, title: card, click, point, show, locate, type, clearField, waitText, open, section } = ctx;

  async function pick(match) {
    await waitText('Выберите сертификат ЭЦП');
    await caption('Выбор ключа ЭЦП', 'В рабочей версии — окно NCALayer, в прототипе — тестовый сертификат для этого сценария');
    await sleep(700);
    if (!(await locate(match, '.ecp-item'))) {
      await click('Показать', 'button');
      await sleep(400);
    }
    await click(match, '.ecp-item');
    await caption('Проверка ЭЦП', 'Проверяется сертификат, затем — запросы во внешние системы');
  }
  async function begin(cert) {
    await click('Выбрать ключ ЭЦП', 'button');
    await pick(cert);
  }
  /** Галочка согласия → «Далее» → пароль → «Завершить регистрацию» (быстро, для второстепенных веток). */
  async function finishQuick(pass) {
    await caption('Согласие и пароль', 'Дальше — как в сценарии 1: согласие на обработку ПД, пароль, завершение');
    await show('Я принимаю', 'label');
    await click('Я принимаю', 'label');
    await sleep(400);
    await click('Далее', 'button');
    await waitText('Придумайте пароль');
    await type('#reg-pass', pass, 45);
    await type('#reg-pass2', pass, 45);
    await sleep(500);
    await click('Завершить регистрацию', 'button');
    await waitText('Регистрация завершена');
    await sleep(900);
  }

  await card('Портал МЗ РК · прототип', 'Регистрация пользователей',
    'ЭЦП → проверки КГД / справочник госорганов / СУР → выбор профиля → данные из ГБД и согласие на обработку ПД → пароль.', 5600);

  // ── 1. ЭЦП ФЛ, ИП подтверждён — полный проход ─────────────────────
  await section('ФЛ с ИП', async () => {
    await card('Сценарий 1', 'Личная ЭЦП ФЛ, ИП подтверждён в КГД', 'Полный проход регистрации и сразу — вход на портал.');
    await point('Подпишите ключом ЭЦП', 'li');
    await say('Старт', 'Перед началом — четыре шага регистрации, чтобы пользователь понимал, что его ждёт', 3400);
    await begin('Касымов');
    await caption('Стадия 1 · Проверки', 'Проверяется ЭЦП, определяются ИИН и тип ЭЦП, затем статус ИП в ИС КГД — до формирования списка профилей');
    await waitText('Выберите профиль');
    await sleep(1600);
    await point('Статус ИП подтверждён', 'div[role=status]');
    await say('КГД подтвердила ИП', 'Уведомление «Статус ИП подтверждён» — доступны два профиля: «Гражданин» и «Бизнес»');
    await point('Уровень: Заявитель', 'span');
    await say('Уровень и роль', 'LEVEL и ROLE показаны, но не выбираются: Заявитель, специалист с правом подписи — для обоих профилей');
    await point('изменить их нельзя', 'div');
    await say('Подменить нельзя', 'Организацию, БИН, уровень и роль пользователь не выбирает — только сам профиль');
    await click('ИП Касымов', 'button.opt');
    await say('Выбор профиля', 'Выбран профиль «Бизнес» (ИП). Дальше — «Продолжить регистрацию»', 2600);
    await click('Продолжить регистрацию', 'button');
    await caption('Запрос в ГБД ФЛ', 'После «Продолжить регистрацию» — запрос в ГБД ФЛ по ИИН. До этого момента ГБД не вызывается');
    await waitText('Сведения получены');
    await sleep(1400);
    await say('Данные из ГБД ФЛ', 'Анкету заполнять не нужно. Данные только для проверки — исправляются через ЦОН, не на портале');
    await show('Я принимаю', 'label');
    await point('Далее', 'button');
    await say('Согласие на обработку ПД', 'Пока галочка не стоит, кнопка «Далее» недоступна — перейти к созданию пароля нельзя');
    await click('Я принимаю', 'label');
    await say('Согласие принято', 'Сохраняются факт согласия, дата и время. Кнопка «Далее» стала активной', 2800);
    await click('Далее', 'button');
    await waitText('Придумайте пароль');
    await say('Создание пароля', 'Логин — ИИН, его вводить не нужно. Требования к паролю подсвечиваются по мере ввода', 3000);
    await type('#reg-pass', 'parol', 150);
    await say('Требования постановки', 'Не менее 8 символов, заглавная и строчная буква, спецсимвол — сразу видно, чего не хватает', 3400);
    await type('#reg-pass', '#2026X', 150);
    await sleep(1200);
    await type('#reg-pass2', 'parol#2026', 90);
    await page_tab(ctx);
    await waitText('Пароли не совпадают.');
    await say('Пароли не совпадают.', 'Текст ошибки по постановке. Кнопка «Завершить регистрацию» недоступна', 3400);
    await clearField('#reg-pass2');
    await type('#reg-pass2', 'parol#2026X', 90);
    await say('Пароли совпадают', 'Все требования выполнены — можно завершать', 2400);
    await click('Завершить регистрацию', 'button');
    await waitText('Регистрация завершена');
    await sleep(1000);
    await say('Регистрация завершена', 'Созданы пользователь и профиль. В итоге — логин и дата и время согласия на обработку ПД', 4000);
    await point('Войти на портал', 'button');
    await say('Сразу ко входу', 'Ключ ЭЦП и профиль передаются на вход — останется ввести пароль', 2800);
    await click('Войти на портал', 'button');
    await waitText('Введите пароль', 15000);
    await sleep(1000);
    await type('#login-pass', 'parol#2026X', 80);
    await caption('Вход', 'Пароль, заданный при регистрации, — и пользователь в кабинете');
    await click('Войти', 'button[type=submit]');
    await sleep(3000);
    await say('Вход выполнен', 'Профиль «Бизнес» (ИП) → кабинет бизнеса', 3000);
  });

  // ── 2. ЭЦП ФЛ без ИП ──────────────────────────────────────────────
  await section('ФЛ без ИП', async () => {
    await open('Регистрация.dc.html', { reset: true });
    await card('Сценарий 2', 'Личная ЭЦП ФЛ, ИП не подтверждён', 'КГД не подтверждает статус ИП — доступен только профиль «Гражданин».');
    await begin('Нурланова');
    await waitText('Выберите профиль');
    await sleep(1400);
    await say('Только «Гражданин»', 'ИС КГД не подтвердила ИП — пользователь видит, почему доступен один профиль. LEVEL Заявитель, ROLE специалист с правом подписи', 5000);
  });

  // ── 3. ЭЦП ЮЛ, медорганизация ─────────────────────────────────────
  await section('ЮЛ медорганизация', async () => {
    await open('Регистрация.dc.html', { reset: true });
    await card('Сценарий 3', 'ЭЦП ЮЛ · медицинская организация', 'БИН нет в справочнике госорганов → запрос в ИС СУР, БИН из СУР совпал с БИН из ЭЦП.');
    await begin('Омарова');
    await caption('Проверки ЭЦП ЮЛ', 'Из ЭЦП — ИИН сотрудника, БИН и право подписи. Справочник organization_go → не найден → ИС СУР: GetMoFpPersonalIin, затем GetMoInfoItems и сверка БИН');
    await waitText('Выберите профиль');
    await sleep(2400);
    await say('Два профиля', 'СУР подтвердила медорганизацию: «Медперсонал» (MEDICAL / MEDICAL_STAFF) и «Бизнес» (роль — по праву подписи из ЭЦП)', 4600);
    await click('Продолжить регистрацию', 'button');
    await waitText('Сведения получены');
    await sleep(1200);
    await say('Данные из ГБД ЮЛ', 'Запрос по БИН в ГБД ЮЛ. ГБД ФЛ не вызывается — данные сотрудника берутся из сертификата', 3800);
    await show('Сотрудник', 'div');
    await sleep(1800);
    await finishQuick('Medic#2026');
    await say('Готово', 'Профиль «Медперсонал» зарегистрирован', 2600);
  });

  // ── 4. Госорган ───────────────────────────────────────────────────
  await section('госорган', async () => {
    await open('Регистрация.dc.html', { reset: true });
    await card('Сценарий 4', 'ЭЦП ЮЛ · государственный орган', 'БИН найден во внутреннем справочнике organization_go — ИС СУР не вызывается.');
    await begin('Жумабаева');
    await caption('Справочник госорганов', 'БИН найден в organization_go — запрос в ИС СУР не выполняется');
    await waitText('Выберите профиль');
    await sleep(1600);
    await point('Роль назначит администратор', 'span');
    await say('Государственный орган', 'LEVEL определяется организацией, ROLE не присваивается — её назначит администратор. Признак права подписи из ЭЦП сохраняется', 5000);
    await click('Продолжить регистрацию', 'button');
    await waitText('Сведения получены');
    await sleep(1000);
    await finishQuick('Gov#Pass2026');
    await show('Роль в системе назначит администратор', 'div[role=note]');
    await say('Итог для госоргана', 'Отдельная подсказка: до назначения роли администратором функции госоргана недоступны', 3800);
  });

  // ── 5. ЮЛ без права подписи ───────────────────────────────────────
  await section('ЮЛ без подписи', async () => {
    await open('Регистрация.dc.html', { reset: true });
    await card('Сценарий 5', 'ЭЦП ЮЛ · не медорганизация, без права подписи', 'СУР не подтверждает организацию как медицинскую — доступен только «Бизнес».');
    await begin('Ибраев');
    await waitText('Выберите профиль');
    await sleep(1600);
    await say('Только «Бизнес»', 'Организация не подтверждена в ИС СУР как медицинская. У сотрудника нет права подписи → ROLE «специалист без права подписи»', 5000);
  });

  // ── 6. Добавление профиля существующему пользователю ──────────────
  await section('добавление профиля', async () => {
    await open('Регистрация.dc.html', { reset: true });
    await card('Сценарий 6', 'Пользователь уже есть — добавляем профиль', 'Один ИИН — один пользователь, но профилей у него может быть несколько.');
    await begin('Ахметов');
    await waitText('Выберите профиль');
    await sleep(1600);
    await point('Уже зарегистрирован', 'span');
    await say('Уже зарегистрированный профиль', '«Медперсонал» уже есть у этого пользователя — он недоступен. «Бизнес» можно добавить', 3800);
    await point('У вас уже есть учётная запись', 'div[role=note]');
    await say('Без дубликата', 'Новый профиль добавляется к существующей учётной записи — логин и пароль прежние', 3400);
    await click('Продолжить регистрацию', 'button');
    await waitText('Сведения получены');
    await sleep(1000);
    await show('Я принимаю', 'label');
    await click('Я принимаю', 'label');
    await sleep(500);
    await click('Добавить профиль', 'button');
    await waitText('Профиль добавлен');
    await sleep(1000);
    await say('Профиль добавлен', 'Шаг создания пароля пропущен: у пользователя уже есть пароль', 3400);
  });

  // ── 7. Уже зарегистрирован ────────────────────────────────────────
  await section('уже зарегистрирован', async () => {
    await open('Регистрация.dc.html', { reset: true });
    await card('Сценарий 7', 'Пользователь уже зарегистрирован', 'Все доступные по ЭЦП профили уже зарегистрированы.');
    await begin('ИИН 920315401540');
    await waitText('Учётная запись уже есть');
    await sleep(900);
    await say('Нужна авторизация', 'Текст по постановке: «Пользователь уже зарегистрирован в системе. Для продолжения работы пройдите авторизацию.»', 4800);
    await point('Войти', 'button.btn-p');
    await say('Кнопка «Войти»', 'Переводит на вход с тем же ключом ЭЦП', 2600);
  });

  await card('Итого', 'Регистрация — основные сценарии', 'Профили формируются только по ЭЦП, КГД, справочнику и СУР. ГБД вызывается один раз после выбора профиля. Без согласия на обработку ПД дальше не пройти.', 6000);
}

/** Уход фокуса с поля повтора пароля — чтобы сработала проверка совпадения. */
async function page_tab(ctx) {
  await ctx.page.keyboard.press('Tab');
  await ctx.sleep(300);
}
