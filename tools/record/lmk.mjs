/**
 * Видео «Медицинская книжка» — интеграция с ЛМК (UC9.14, сервис EH_GET_ALL_LMK)
 * в личном кабинете гражданина.
 *
 *   npm run record -- lmk   → exports/video/8. Медицинская книжка.mp4
 *
 * Вход в раздел из меню кабинета, обложка книжки и допуск к работе, обследования,
 * сведения о владельце и медицинские сведения, переключение книжек, затем ответы
 * сервиса из панели «Прототип»: допуск истекает, не допущен, неполные сведения,
 * книжки нет, сервис недоступен, медленный ответ.
 */

export const title = 'Медицинская книжка';
export const fileName = '8. Медицинская книжка';
export const start = 'Личный кабинет.dc.html';

export default async function record(ctx) {
  const { page, sleep, caption, say, title: card, click, point, show, waitText, open, section } = ctx;

  const PANEL = 'Прототип';
  async function scn(label) {
    await caption('Панель «Прототип»', 'Ответ сервиса ЛМК: «' + label + '»');
    await click(PANEL, '.lm-pp > button');
    await sleep(400);
    await click(label, 'button[role=radio]');
    await click(PANEL, '.lm-pp > button');
    await sleep(300);
  }
  const top = () => page.evaluate(() => window.scrollTo({ top: 0, behavior: 'smooth' })).then(() => sleep(700));

  await card('Портал МЗ РК · личный кабинет гражданина', 'Личная медицинская книжка',
    'Интеграция с ЛМК: сведения о книжках гражданина из сервиса EH_GET_ALL_LMK по ИИН.', 5200);

  // ── 1. Вход в раздел ──────────────────────────────────────────────
  await section('вход в раздел', async () => {
    await open('Личный кабинет.dc.html');
    await page.evaluate(() => sessionStorage.removeItem('mp-lmk-scn'));
    await point('Медицинская книжка', 'a.cn-it');
    await say('Личный кабинет', 'Новый раздел «Медицинская книжка» — в меню кабинета, рядом с паспортом здоровья', 3600);
    await click('Медицинская книжка', 'a.cn-it');
    await sleep(300);
    await say('Загрузка', 'Пока сервис отвечает, на месте данных — скелет страницы', 1200);
    await waitText('Обновлено сегодня', 15000);
    await sleep(500);
  });

  // ── 2. Книжки и допуск к работе ───────────────────────────────────
  await section('книжки', async () => {
    await point('AA004517', 'button[role=tab]');
    await say('Все книжки', 'Сервис возвращает все книжки гражданина — по одной на место работы. Действующая — первой', 4000);
    await point('AA001183', 'button[role=tab]');
    await say('Прежняя книжка', 'Книжка с прошлого места работы со сроком, который истёк, — серым, как архив', 3600);
  });

  await section('обложка', async () => {
    await point('Медицинская книжка', '.lm-cover-eb');
    await say('Обложка', 'Номер книжки, должность и место работы — как на бланке', 3200);
    await click('', 'button[aria-label="Скопировать номер книжки"]');
    await waitText('Номер книжки скопирован');
    await say('Номер', 'Номер копируется одним нажатием', 2400);
    await point('Скачать PDF', 'a');
    await say('PDF', 'Готовый документ из сервиса: скачать или открыть для печати', 3200);
  });

  await section('допуск', async () => {
    await point('Допущен к работе до', '.lm-st-t');
    await say('Допуск к работе', 'Главное — сразу: допущен ли к работе, до какой даты и сколько дней осталось', 4000);
    await point('', '.lm-prog');
    await say('Срок', 'Полоса показывает, какая часть срока допуска уже прошла', 3000);
    await point('Подписано ЭЦП терапевта', '.lm-sign');
    await say('ЭЦП', 'Заключение терапевта подписано ЭЦП', 2600);
    await point('Вид медосмотра', '.lm-facts > div');
    await say('Заключение', 'Вид медосмотра, дата заключения, терапевт и медорганизация с населённым пунктом', 3800);
  });

  // ── 3. Обследования и сведения ────────────────────────────────────
  await section('обследования', async () => {
    await show('Обследования и осмотры', 'h2', 'start');
    await sleep(500);
    await point('Результаты:', '.lm-sum .lm-badge');
    await say('Обследования', 'Восемь позиций в порядке бланка книжки. Сверху — сколько из них с результатами', 3800);
    await point('Обследование на туберкулёз', '.lm-ex-name');
    await say('Результат', 'Значок — без отклонений, справа — дата. Ниже заключение врача, врач и медорганизация', 4200);
    await point('Сведения о владельце', 'h2');
    await say('Сведения о владельце', 'Рядом — основная профессия, целевая группа, телефон и место жительства', 3600);
    await point('Медицинские сведения', 'h2');
    await say('Медицинские сведения', 'Противопоказания, перенесённые инфекции и прививки — в одной компактной карточке', 3800);
    await show('Гигиеническое обучение', 'h2');
    await say('Гигиеническое обучение', 'Если сервис прислал сведения об обучении — они под обследованиями', 3200);
    await top();
  });

  await section('другая книжка', async () => {
    await click('AA001183', 'button[role=tab]');
    await sleep(600);
    await say('Прежняя книжка', 'Переключение без перезагрузки: срок допуска истёк, обследований меньше', 3600);
    await click('AA004517', 'button[role=tab]');
    await sleep(500);
  });

  await section('обновить', async () => {
    await click('Обновить', 'button');
    await waitText('Сведения обновлены', 6000);
    await say('Обновить', 'Повторный запрос в сервис. Показанные данные не пропадают, пока идёт ответ', 3400);
  });

  // ── 4. Ответы сервиса ─────────────────────────────────────────────
  await section('допуск истекает', async () => {
    await card('Ответы сервиса', 'Состояния книжки', 'Сценарии переключаются панелью «Прототип» слева внизу.', 3600);
    await scn('Допуск истекает');
    await waitText('Осталось 18 дней', 8000);
    await sleep(400);
    await point('Пройдите периодический медосмотр', '.lm-st-act span');
    await say('Допуск истекает', 'За 30 дней до конца срока — подсказка пройти медосмотр и переход к списку медорганизаций', 4200);
  });

  await section('не допущен', async () => {
    await scn('Не допущен');
    await waitText('Не допущен к работе', 8000);
    await sleep(400);
    await point('Отклонения и противопоказания', '.lm-st-act');
    await say('Не допущен', 'Отклонения и противопоказания — сразу в блоке допуска, без поиска по странице', 4000);
    await show('Бактериологическое исследование', '.lm-ex-name');
    await say('Отклонения', 'В списке обследований такие позиции отмечены красным', 3000);
    await top();
  });

  await section('неполные сведения', async () => {
    await scn('Неполные сведения');
    await waitText('Срок допуска не указан', 8000);
    await sleep(400);
    await say('Неполные сведения', 'Как в тестовом ответе: нет срока допуска, МО — только кодом. Пустые позиции — «Нет сведений»', 4400);
  });

  await section('книжки нет', async () => {
    await scn('Книжки нет');
    await waitText('Медицинская книжка не найдена', 8000);
    await sleep(400);
    await say('Книжки нет', 'Подсказка, когда книжка появится, и переход к медорганизациям', 3200);
  });

  await section('сервис недоступен', async () => {
    await scn('Сервис недоступен');
    await waitText('Не удалось получить сведения', 8000);
    await sleep(400);
    await say('Сервис недоступен', 'Сообщение об ошибке и «Повторить»', 2800);
  });

  await section('медленный ответ', async () => {
    await scn('Медленный ответ');
    await sleep(600);
    await say('Медленный ответ', 'Скелет страницы держит раскладку, пока сервис отвечает', 2400);
    await waitText('Обновлено сегодня', 8000);
    await sleep(600);
    await scn('Две книжки');
    await waitText('Обновлено сегодня', 8000);
    await sleep(600);
  });

  await card('Портал МЗ РК', 'Личная медицинская книжка', 'Все книжки гражданина, допуск к работе, обследования и PDF. Работает на планшетах и телефонах.', 4400);
}
