/**
 * Видео «Личная медицинская карта» — интеграция с ЛМК (UC9.14, сервис EH_GET_ALL_LMK)
 * в личном кабинете гражданина, по макету аналитика.
 *
 *   npm run record -- lmk   → exports/video/8. Личная медицинская карта.mp4
 *
 * Вход из меню кабинета, текущий медицинский статус, сведения о работе, медицинское заключение
 * (выбор услуги), перенесённые инфекции, прививки, затем ответы сервиса из панели «Прототип».
 */

export const title = 'Личная медицинская карта';
export const fileName = '8. Личная медицинская карта';
export const start = 'Личный кабинет.dc.html';

export default async function record(ctx) {
  const { page, sleep, caption, say, title: card, click, point, show, waitText, open, section } = ctx;

  async function scn(label) {
    await caption('Панель «Прототип»', 'Ответ сервиса ЛМК: «' + label + '»');
    await click('Прототип', '.lm-pp > button');
    await sleep(400);
    await click(label, 'button[role=radio]');
    await click('Прототип', '.lm-pp > button');
    await sleep(300);
  }
  const top = () => page.evaluate(() => window.scrollTo({ top: 0, behavior: 'smooth' })).then(() => sleep(700));

  await card('Портал МЗ РК · личный кабинет гражданина', 'Личная медицинская карта',
    'UC9.14 «Интеграция с ЛМК»: сведения из сервиса EH_GET_ALL_LMK по ИИН. Поля — строго по постановке, раскладка — по макету.', 5600);

  await section('вход в раздел', async () => {
    await open('Личный кабинет.dc.html');
    await page.evaluate(() => sessionStorage.removeItem('mp-lmk-scn'));
    await point('Личная медицинская карта', 'a.cn-it');
    await say('Меню кабинета', 'Обзор, Личная медицинская карта и Уведомления — лишние разделы убраны', 3600);
    await click('Личная медицинская карта', 'a.cn-it');
    await waitText('Текущий медицинский статус', 15000);
    await sleep(600);
  });

  await section('статус', async () => {
    await point('Текущий медицинский статус', 'h2');
    await say('Текущий медицинский статус', 'Допуск к работе — по записи «Допуск к работе» из ответа сервиса', 3600);
    await point('Активен: Допущен', '.lm-seg-b');
    await say('Статус', 'Записей ЛМК может быть несколько — переключение по статусу: допущен, срок истёк, не допущен', 4400);
    await point('Противопоказания', '.lm-banner-t');
    await say('Противопоказания', 'В строке статуса — противопоказания из ответа сервиса', 3000);
    await point('Тип медицинского осмотра', '.lm-tile');
    await say('Сведения о допуске', 'Тип медицинского осмотра, дата выдачи, срок действия, ответственный врач и медорганизация', 4400);
    await point('Срок действия', '.lm-tile');
    await say('Срок действия', 'Дата окончания, дата начала и сколько дней осталось', 3000);
  });

  await section('работа и заключение', async () => {
    await show('Сведения о работе', 'h2');
    await point('Сведения о работе', 'h2');
    await say('Сведения о работе', 'Место работы, должность, основная профессия и целевая группа', 3400);
    await point('Медицинское заключение', 'h2');
    await say('Медицинское заключение', 'Дата заключения, ФИО врача, организация и само заключение врача', 3600);
    await click('', 'button.lm-sel');
    await sleep(600);
    await say('Медицинские услуги', 'Заключений несколько — по одному на услугу. Выбор — в списке, отклонения отмечены красным', 4200);
    await click('Терапевт', 'button.lm-opt');
    await sleep(700);
    await say('Терапевт', 'Заключение терапевта открыто без перехода и перезагрузки', 3000);
  });

  await section('инфекции и прививки', async () => {
    await show('Ранее перенесённые инфекционные заболевания', 'h2', 'start');
    await sleep(500);
    await say('Перенесённые инфекции', 'Код, наименование и дата перенесённого заболевания', 3200);
    await show('Сведения о полученных прививках', 'h2', 'start');
    await sleep(500);
    await say('Прививки', 'Название вакцины, дата вакцинации и ID вакцинации', 3000);
    await click('Показать ещё', 'button');
    await sleep(600);
    await say('Показать ещё', 'Длинный список раскрывается на месте', 2600);
    await top();
  });

  await section('другая запись', async () => {
    await click('Срок истёк', '.lm-seg-b');
    await sleep(700);
    await say('Срок истёк', 'Запись с прежнего места работы: срок действия истёк', 3000);
    await click('Активен: Допущен', '.lm-seg-b');
    await sleep(500);
  });

  await section('pdf и обновление', async () => {
    await point('Экспорт в PDF', 'a');
    await say('Экспорт в PDF', 'Документ из ответа сервиса', 2600);
    await click('Обновить данные', 'button');
    await waitText('Данные обновлены', 6000);
    await say('Обновить данные', 'Повторный запрос в сервис, показанные данные при этом не пропадают', 3200);
  });

  await section('не допущен', async () => {
    await card('Ответы сервиса', 'Другие сценарии', 'Переключаются панелью «Прототип» слева внизу.', 3400);
    await scn('Не допущен');
    await waitText('Отклонения в заключениях', 8000);
    await sleep(500);
    await point('Противопоказания', '.lm-banner-t');
    await say('Не допущен', 'Противопоказания и услуги с отклонениями — сразу в строке статуса', 3800);
    // блок заключения — над субтитром: прокручиваем так, чтобы карточка встала под шапку
    await page.evaluate(() => { const el = document.getElementById('lm-md-h'); if(el) window.scrollTo({ top: el.getBoundingClientRect().top + window.scrollY - 100, behavior: 'smooth' }); });
    await sleep(900);
    await say('Заключение', 'По умолчанию открыто заключение с отклонениями', 3000);
    await top();
  });

  await section('срок истекает', async () => {
    await scn('Срок истекает');
    await waitText('осталось 18 дней', 8000);
    await sleep(400);
    await point('Срок действия', '.lm-tile');
    await say('Срок истекает', 'За 30 дней до окончания срок действия подсвечивается', 3000);
  });

  await section('неполные сведения', async () => {
    await scn('Неполные сведения');
    await waitText('Код МО 840', 8000);
    await sleep(400);
    await say('Неполные сведения', 'Как в тестовом ответе: без срока допуска, МО — только кодом. Пустые поля не показываются', 4200);
  });

  await section('нет записей и ошибка', async () => {
    await scn('Записей нет');
    await waitText('Сведений личной медицинской карты нет', 8000);
    await say('Записей нет', 'Сообщение и «Проверить снова»', 2600);
    await scn('Сервис недоступен');
    await waitText('Не удалось получить сведения', 8000);
    await say('Сервис недоступен', 'Сообщение об ошибке и «Повторить»', 2600);
    await scn('Медленный ответ');
    await sleep(500);
    await say('Медленный ответ', 'Пока сервис отвечает — скелет страницы', 2200);
    await waitText('Текущий медицинский статус', 8000);
    await scn('Две записи');
    await waitText('Текущий медицинский статус', 8000);
    await sleep(500);
  });

  await card('Портал МЗ РК', 'Личная медицинская карта', 'По макету и постановке UC9.14. Работает на планшетах и телефонах.', 4200);
}
