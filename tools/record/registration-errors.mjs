/**
 * Видео «Регистрация — ошибки и исключения» — раздел 12 постановки.
 *
 *   npm run record -- registration-errors   → exports/video/3. Регистрация — ошибки и исключения.mp4
 *
 * КГД недоступна и тайм-аут, СУР недоступна, сотрудник не найден в СУР,
 * ГБД недоступна, организация не найдена в ГБД ЮЛ, некорректный сертификат,
 * NCALayer не запущен, учётная запись INACTIVE.
 */

export const title = 'Регистрация — ошибки и исключения';
export const fileName = '3. Регистрация — ошибки и исключения';
export const start = 'Регистрация.dc.html';

export default async function record(ctx) {
  const { sleep, caption, say, title: card, click, point, locate, waitText, open, section } = ctx;

  async function pick(match) {
    await waitText('Выберите сертификат ЭЦП');
    await caption('Выбор ключа ЭЦП', 'В рабочей версии — окно NCALayer, в прототипе — тестовый сертификат для этого сценария');
    await sleep(700);
    if (!(await locate(match, '.ecp-item'))) {
      await click('Показать', 'button');
      await sleep(400);
    }
    await click(match, '.ecp-item');
    await caption('Проверка ЭЦП', 'Проверяется сертификат, затем — запросы во внешние системы');
  }
  /** Открыть окно ЭЦП с того экрана, где мы сейчас. */
  async function openEcp() {
    for (const label of ['Выбрать другой ключ', 'Выбрать ключ ЭЦП', 'Повторить']) {
      if (await locate(label, 'button')) { await click(label, 'button'); return; }
    }
    throw new Error('нет кнопки выбора ключа');
  }

  await card('Портал МЗ РК · прототип', 'Регистрация — ошибки и исключения',
    'Как обрабатываются тайм-ауты, недоступность внешних систем, отсутствие сотрудника и организации, некорректный сертификат.', 5600);

  // ── КГД ───────────────────────────────────────────────────────────
  await section('КГД', async () => {
    await card('ИС КГД', 'Проверка статуса ИП не выполнена', 'Сервис недоступен или не ответил вовремя.');
    await openEcp();
    await pick('КГД недоступна');
    await waitText('ИС КГД не ответила');
    await sleep(900);
    await say('КГД недоступна', 'Текст по постановке: «Не удалось получить сведения о статусе индивидуального предпринимателя. Повторите попытку позже.»', 5200);
    await point('Повторить попытку', 'button');
    await say('Повторить попытку', 'Проверки запускаются заново с тем же ключом — выбирать ЭЦП снова не нужно', 3000);
    await click('Повторить попытку', 'button');
    await waitText('ИС КГД не ответила');
    await sleep(800);
    await openEcp();
    await pick('КГД: тайм-аут');
    await waitText('ИС КГД не ответила');
    await sleep(900);
    await point('Сервис не ответил вовремя', 'span');
    await say('Тайм-аут', 'В строке проверки — «Сервис не ответил вовремя», пользователю — то же сообщение КГД с повтором', 4000);
  });

  // ── СУР ───────────────────────────────────────────────────────────
  await section('СУР', async () => {
    await card('ИС СУР', 'Проверка сотрудника не выполнена', 'СУР недоступна или сотрудник в ней не найден.');
    await openEcp();
    await pick('СУР недоступна');
    await waitText('ИС СУР не ответила');
    await sleep(900);
    await say('СУР недоступна', 'Текст по постановке: «Не удалось проверить сведения о сотруднике. Повторите попытку позже.»', 4600);
    await openEcp();
    await pick('Нет в СУР');
    await waitText('Сотрудник не найден в ИС СУР');
    await sleep(900);
    await say('Сотрудник не найден в СУР', 'Текст по постановке: «Не подтверждена принадлежность к указанной организации. Регистрация невозможна.» Повтора нет — только другой ключ', 5400);
  });

  // ── ГБД ───────────────────────────────────────────────────────────
  await section('ГБД', async () => {
    await card('ГБД ФЛ / ГБД ЮЛ', 'Сведения из ГБД не получены', 'Ошибка возникает после выбора профиля и «Продолжить регистрацию».');
    await openEcp();
    await pick('ГБД недоступна');
    await waitText('Выберите профиль');
    await sleep(1200);
    await click('Продолжить регистрацию', 'button');
    await waitText('ГБД ФЛ не ответила');
    await sleep(900);
    await say('ГБД недоступна', 'Текст по постановке: «Не удалось получить необходимые сведения. Повторите попытку позже.» Можно повторить запрос или вернуться к профилю', 5200);
    await open('Регистрация.dc.html', { reset: true });
    await openEcp();
    await pick('Нет в ГБД ЮЛ');
    await waitText('Выберите профиль');
    await sleep(1200);
    await click('Продолжить регистрацию', 'button');
    await waitText('Организация не найдена');
    await sleep(900);
    await say('Организация не найдена', 'ГБД ЮЛ не вернула сведения по БИН — регистрация невозможна, повтор не предлагается', 4000);
  });

  // ── Сертификат ────────────────────────────────────────────────────
  await section('сертификат', async () => {
    await card('Сертификат ЭЦП', 'Некорректный сертификат', 'Дальше проверки ЭЦП не пускаем: просрочен, отозван, выбран не тот ключ, NCALayer не запущен.');
    const cases = [
      ['Срок истёк', 'Срок действия сертификата истёк', 'Показываем дату окончания и куда обратиться за новым ключом'],
      ['Отозван', 'Сертификат отозван', 'Нужен действующий ключ ЭЦП'],
      ['Ключ подписи', 'Выбран ключ для подписания документов', 'Подсказываем, как отличить ключ аутентификации'],
      ['NCALayer не запущен', 'NCALayer не запущен', 'Подпись не получена — запустить NCALayer и повторить или скачать его'],
    ];
    for (const [cert, head, text] of cases) {
      await openEcp();
      await pick(cert);
      await waitText(head);
      await sleep(900);
      await say(head, text, 3600);
    }
  });

  // ── INACTIVE ──────────────────────────────────────────────────────
  await section('inactive', async () => {
    await card('Учётная запись', 'Пользователь заблокирован', 'Учётная запись с этим ИИН есть, но её статус — INACTIVE.');
    await openEcp();
    await pick('Учётка заблокирована');
    await waitText('Учетная запись недоступна');
    await sleep(900);
    await say('Регистрация невозможна', '«Учетная запись недоступна. Обратитесь к администратору системы.»', 3800);
  });

  await card('Итого', 'Ошибки внешних систем', 'Для каждой ошибки — понятный текст из постановки и следующий шаг: повторить, выбрать другой ключ или вернуться к профилю.', 5600);
  await caption('', '');
}
