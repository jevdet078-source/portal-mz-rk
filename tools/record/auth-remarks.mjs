/**
 * Видео «Вход и регистрация — доработки по замечаниям аналитика».
 *
 *   npm run record -- auth-remarks   → exports/video/4. Вход и регистрация — доработки.mp4
 *
 * Показывает только то, что изменилось после тестирования (документы аналитика
 * «Авторизация» и «Регистрация» с комментариями к скриншотам), без полного прохода сценариев.
 */

export const title = 'Вход и регистрация — доработки';
export const fileName = '4. Вход и регистрация — доработки';
export const start = 'Вход.dc.html';

export default async function record(ctx) {
  const { sleep, caption, say, title: card, click, point, show, locate, type, waitText, open, section } = ctx;

  /** Выбрать тестовый сертификат в окне ЭЦП (группа ошибок раскрывается при необходимости). */
  async function pick(match) {
    await caption('Выбор ключа ЭЦП', 'В прототипе — тестовый сертификат для следующего примера');
    await waitText('Выберите сертификат ЭЦП');
    await sleep(600);
    if (!(await locate(match, '.ecp-item'))) {
      await click('Показать', 'button');
      await sleep(400);
    }
    await click(match, '.ecp-item');
  }
  /** Открыть окно ЭЦП с того экрана, где мы сейчас. */
  async function openEcp() {
    for (const label of ['Войти с другим ключом', 'Выбрать другой ключ', 'Выбрать другой сертификат', 'Выбрать ключ ЭЦП', 'Войти с ЭЦП']) {
      if (await locate(label, 'button')) { await click(label, 'button'); return; }
    }
    throw new Error('нет кнопки выбора ключа');
  }
  /** Экран сертификата: галочка согласия → «Далее». */
  async function consentNext() {
    await waitText('Владелец');
    await sleep(500);
    await show('Я принимаю', 'label');
    await click('Я принимаю', 'label');
    await sleep(300);
    await click('Далее', 'button');
  }

  await card('Портал МЗ РК · прототип', 'Вход и регистрация — доработки',
    'Только то, что изменилось по замечаниям аналитика после тестирования.', 4600);

  // ── Вход ─────────────────────────────────────────────────────────
  await section('вход: старт', async () => {
    await card('Авторизация', 'Экран входа', 'Лишний текст убран, добавлены обязательные уведомления.');
    await point('Подпишите вход ключом ЭЦП', 'p');
    await say('Заголовок', 'Только «Вход» и «Подпишите вход ключом ЭЦП.» — слово «портал» и пояснения про логин убраны', 3800);
    await point('многофакторная аутентификация', 'div[role=note]');
    await say('Уведомление о безопасности', 'Добавлено: в процессе регистрации применяется многофакторная аутентификация (обязательное подписание ЭЦП)', 4200);
    await point('Скачать NCALayer', 'a');
    await say('NCALayer', '«Понадобится запущенный NCALayer и ключ ЭЦП: Скачать NCALayer» — без уточнений про виды ключей', 3800);
    await point('ст. 641 КоАП', 'p');
    await say('Левая панель', 'Вместо списка преимуществ — заголовок и предупреждение о конфиденциальности по ст. 641 КоАП РК', 4200);
  });

  await section('вход: ошибки', async () => {
    await card('Авторизация', 'Ошибки — плашкой, а не заголовком', 'Список внутренних проверок системы больше не показывается.');
    await click('Войти с ЭЦП', 'button');
    await pick('Касымов');
    await caption('Проверка ЭЦП', 'Внутренние проверки не выводятся — пользователь видит только «Проверяем ЭЦП…» на кнопке');
    await waitText('Вы ещё не зарегистрированы');
    await sleep(900);
    await point('Вы ещё не зарегистрированы', 'div[role=alert]');
    await say('Не зарегистрирован', 'Заголовок «Вход» не меняется, ошибка — плашкой. Главное действие — «Зарегистрироваться» (ключ передаётся в регистрацию)', 4600);
    await openEcp();
    await pick('Учётка заблокирована');
    await waitText('Учетная запись недоступна');
    await sleep(900);
    await say('Учётная запись недоступна', 'Так же — одной плашкой под неизменным заголовком', 3200);
  });

  await section('вход: профиль и пароль', async () => {
    await card('Авторизация', 'Профиль и пароль', 'Убрана лишняя информация.');
    await openEcp();
    await pick('ИИН 920315401540');
    await waitText('Выберите профиль');
    await sleep(1000);
    await say('Выбор профиля', 'Убраны блок с данными ЭЦП, подзаголовок, уровень и роль — только профиль и его реквизиты', 4000);
    await click('Гражданин', 'button.opt');
    await waitText('Введите пароль');
    await sleep(700);
    await point('Логин', 'label');
    await say('Пароль', 'Убраны приветствие и подсказка «ИИН из сертификата — вводить не нужно»; логин по-прежнему подставлен из ЭЦП', 4200);
  });

  // ── Регистрация ──────────────────────────────────────────────────
  await section('регистрация: старт', async () => {
    await open('Регистрация.dc.html', { reset: true });
    await card('Регистрация', 'Стартовый экран', 'Краткая инструкция и обязательные уведомления.');
    await point('Регистрация', 'h2');
    await say('Заголовок', '«Регистрация» — без слова «портал» и без подзаголовка', 3000);
    await point('Придумайте пароль', 'li');
    await say('Краткая инструкция', 'Четыре шага — только заголовками, без пояснений', 3200);
    await point('многофакторная аутентификация', 'div[role=note]');
    await say('Уведомление о безопасности', 'Добавлено уведомление о многофакторной аутентификации', 3200);
    await point('ст. 641 КоАП', 'p');
    await say('Левая панель', '«Регистрация на портале Минздрава» и предупреждение о конфиденциальности вместо непонятного списка', 4000);
  });

  await section('регистрация: сертификат и согласие', async () => {
    await card('Регистрация', 'Данные сертификата вместо экрана проверок', 'Согласие на обработку ПД — на этом же экране.');
    await click('Выбрать ключ ЭЦП', 'button');
    await pick('Касымов');
    await caption('Проверка сертификата', 'Внутренний процесс — только «Проверяем сертификат…» на кнопке');
    await waitText('Владелец');
    await sleep(900);
    await say('Сертификат ЭЦП', 'Показываются данные сертификата: владелец, ИИН, срок действия, серийный номер (для юрлица — ещё организация и БИН)', 4600);
    await show('Я принимаю', 'label');
    await point('Далее', 'button');
    await say('Согласие на обработку ПД', 'Перенесено на этот экран. Пока галочка не стоит, «Далее» недоступна', 3800);
    await click('Я принимаю', 'label');
    await sleep(400);
    await click('Далее', 'button');
    await caption('Проверки в фоне', 'КГД / справочник госорганов / СУР — без отдельного экрана, на кнопке «Проверяем…»');
    await waitText('Выберите профиль');
    await sleep(900);
  });

  await section('регистрация: профиль', async () => {
    await say('Выбор профиля', 'Убраны блок ЭЦП, подзаголовок, уровень, роль и пояснение с замком', 3600);
    await point('ИП подтверждён', 'span');
    await say('Статус ИП — в карточке «Бизнес»', 'Отдельной плашки больше нет: «ИП подтверждён» стоит под «ИП Касымов Е. Б.»', 4000);
    await caption('Другой пример', 'Пользователь, у которого статус ИП не подтверждён');
    await click('Назад', 'button');
    await waitText('Владелец');
    await sleep(500);
    await openEcp();
    await pick('Нурланова');
    await consentNext();
    await waitText('Выберите профиль');
    await sleep(900);
    await point('ИП не подтверждён', 'span');
    await say('ИП не подтверждён', 'Выводится там же: карточка «Бизнес» видна, но недоступна, с причиной', 4000);
  });

  await section('регистрация: пароль и готово', async () => {
    await click('Продолжить регистрацию', 'button');
    await caption('ГБД — в фоне', 'Экран «Проверьте данные» убран: сведения из ГБД запрашиваются в фоне, на кнопке «Получаем данные…»');
    await waitText('Придумайте пароль');
    await sleep(900);
    await say('Пароль', 'Подзаголовок про логин убран — только поля и требования к паролю', 3400);
    await type('#reg-pass', 'Parol#2026', 60);
    await type('#reg-pass2', 'Parol#2026', 60);
    await sleep(400);
    await click('Завершить регистрацию', 'button');
    await waitText('Регистрация завершена');
    await sleep(900);
    await say('Регистрация завершена', 'Остались только зелёная отметка и кнопки — итоговая таблица и пояснения убраны', 4000);
  });

  await section('регистрация: ошибки', async () => {
    await open('Регистрация.dc.html', { reset: true });
    await card('Регистрация', 'Ошибки — плашкой', 'Заголовок шага не меняется, внутренние проверки не показываются.');
    await click('Выбрать ключ ЭЦП', 'button');
    await pick('КГД недоступна');
    await consentNext();
    await waitText('Не удалось получить сведения о статусе');
    await sleep(900);
    await point('Не удалось получить сведения', 'div[role=alert]');
    await say('Ошибка внешней системы', 'Текст из постановки и кнопка «Повторить попытку» — прямо на экране сертификата', 4200);
  });

  await card('Итого', 'Доработки по замечаниям аналитика', 'Меньше текста, ни одного экрана с внутренними проверками, ошибки — плашкой, согласие — на экране сертификата.', 5200);
}
