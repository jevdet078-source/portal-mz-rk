/**
 * Видео «Государственные услуги для бизнеса» — постановка от 28.10.2026.
 *
 *   npm run record -- gov-services-business   → exports/video/22. Государственные услуги для бизнеса.mp4
 *
 * Блок «Услуги» («Все услуги», «Фармацевтика», «Лицензирование и аккредитация»),
 * поиск в пределах категории и «Услуги не найдены», внешние услуги и услуга кабинета,
 * окно «Выберите вид услуги» композитной услуги и переход в кабинет бизнеса.
 */

export const title = 'Государственные услуги для бизнеса';
export const fileName = '22. Государственные услуги для бизнеса';
export const start = 'Государственные услуги.dc.html?for=business';

export default async function record(ctx) {
  const { page, sleep, say, title: card, click, point, type, waitText, open, section } = ctx;

  async function search(text) {
    await type('.gs-search input', text, 110);
    await sleep(700);
  }
  async function clear() {
    await click('', 'button[aria-label="Очистить поиск"]');
    await sleep(500);
  }

  await card('Портал МЗ РК · постановка аналитика', 'Государственные услуги для бизнеса',
    'Категории, поиск в пределах категории и выбор вида композитной услуги «Единого окна».', 5200);

  // ── 1. Структура страницы ─────────────────────────────────────────
  await section('структура', async () => {
    await open('Государственные услуги.dc.html?for=business', { reset: true });
    await waitText('Все услуги', 15000);
    await card('Пункт 1', 'Структура страницы', 'Слева — блок «Услуги» с категориями, справа — название категории, поиск и перечень.');
    await point('Все услуги', 'button.gs-cat');
    await say('Блок «Услуги»', '«Все услуги», «Фармацевтика», «Лицензирование и аккредитация» — со счётчиком услуг', 4000);
    await point('Все услуги', '.gs-h2');
    await say('Справа', 'Название выбранной категории, поиск по наименованию и перечень услуг', 3400);
    await point('Фармацевтика', '.gs-group-head');
    await say('Весь каталог', 'В «Все услуги» перечень разбит по категориям', 3000);
  });

  // ── 2. Внешние и услуги кабинета ──────────────────────────────────
  await section('внешние и кабинет', async () => {
    await card('Пункт 4', 'Где оформляется услуга', 'Услуга кабинета бизнеса и внешние услуги различаются прямо в перечне.');
    await point('Кабинет бизнеса', '.gs-chip');
    await say('Кабинет бизнеса', 'Композитная услуга оформляется здесь, в кабинете бизнеса — фирменный чип', 3800);
    await point('eGov.kz', '.gs-site');
    await say('eGov.kz', 'Внешние услуги — с адресом сайта и стрелкой ↗, открываются в новой вкладке', 3800);
    await point('Е‑лицензирование', '.gs-site');
    await say('«Е-лицензирование»', 'Аналогично для портала «Е-лицензирование»', 2800);
  });

  // ── 3. Выбор категории и поиск ────────────────────────────────────
  await section('категории и поиск', async () => {
    await card('Пункт 2', 'Выбор категории и поиск', 'Поиск фильтрует услуги по наименованию в пределах выбранной категории.');
    await click('Фармацевтика', 'button.gs-cat');
    await sleep(600);
    await say('Фармацевтика', 'Только услуги категории — композитная услуга «Единого окна» и информация о ЛС', 3800);
    await search('лицензи');
    await waitText('Услуги не найдены');
    await sleep(400);
    await say('Услуги не найдены', 'В «Фармацевтике» услуг лицензирования нет — поиск идёт только внутри категории', 4000);
    await point('Искать во всех услугах', 'button.gs-link');
    await say('Подсказка', 'Если совпадения есть в других категориях — можно одним нажатием искать во всех услугах', 3800);
    await click('Искать во всех услугах', 'button.gs-link');
    await sleep(700);
    await say('Все услуги', 'Запрос сохранился, найдены услуги лицензирования; совпадения подсвечены', 3600);
    await clear();
  });

  // ── 4. Окно «Выберите вид услуги» ─────────────────────────────────
  await section('окно', async () => {
    await card('Пункт 3', 'Композитная услуга', 'По нажатию открывается окно «Выберите вид услуги».');
    await click('Фармацевтика', 'button.gs-cat');
    await sleep(500);
    await search('регистрац');
    await sleep(400);
    await click('Композитная', 'button.gs-row');
    await waitText('Выберите вид услуги');
    await sleep(700);
    await point('Лекарственные средства', '.gs-grp');
    await say('Группа', '«Лекарственные средства» — четыре вида услуги', 3000);
    await point('Далее', '.gs-b-pri');
    await say('Далее', 'Пока вид не выбран, кнопка неактивна', 2800);
    await click('Выдача заключения', '.gs-opt');
    await sleep(500);
    await say('Выбор', 'После выбора «Далее» становится активной', 2800);
    await click('Регистрация цены', '.gs-opt');
    await sleep(500);
    await say('Один вариант', 'Выбор другого варианта снимает предыдущий', 2800);
    await click('Отмена', '.gs-b-sec');
    await sleep(600);
    await say('Отмена', 'Окно закрылось без перехода — категория «Фармацевтика» и запрос остались', 3800);
    await click('Композитная', 'button.gs-row');
    await waitText('Выберите вид услуги');
    await sleep(600);
    await say('Повторное открытие', 'Выбор сброшен', 2400);
    await click('', '.gs-x');
    await sleep(500);
    await say('Крестик', 'Закрывает окно так же, как «Отмена». Esc и клик по затемнению — тоже', 3200);
  });

  // ── 5. Далее → кабинет бизнеса ────────────────────────────────────
  await section('далее', async () => {
    await card('Пункт 4', 'Переход в кабинет бизнеса', '«Далее» передаёт выбранный вид услуги в кабинет и открывает сценарий оформления.');
    await click('Композитная', 'button.gs-row');
    await waitText('Выберите вид услуги');
    await sleep(500);
    await click('Казахстанский национальный', '.gs-opt');
    await sleep(400);
    await click('Далее', '.gs-b-pri');
    await waitText('вы вернётесь к услуге', 15000);
    await sleep(1200);
    await say('Без входа', 'Сначала вход с ЭЦП под профилем «Бизнес», после входа — сразу в выбранный сценарий', 4200);
    await page.goBack({ waitUntil: 'networkidle2' });
    await waitText('Фармацевтика', 15000);
    await sleep(1000);
    await say('Назад', 'Вернулись к той же выборке: категория и запрос сохранены', 3200);
    // дальше — как будто вход уже выполнен под профилем «Бизнес»
    await page.evaluate(() => localStorage.setItem('mp-profile', 'business'));
    await click('Композитная', 'button.gs-row');
    await waitText('Выберите вид услуги');
    await sleep(500);
    await click('Казахстанский национальный', '.gs-opt');
    await sleep(400);
    await say('Профиль «Бизнес»', 'Вход уже выполнен — «Далее» ведёт сразу в кабинет', 3000);
    await click('Далее', '.gs-b-pri');
    await page.waitForFunction(() => decodeURIComponent(location.pathname).includes('Заявление КНФ'), { timeout: 20000 });
    await sleep(1500);
    await sleep(1500);
    await say('Кабинет бизнеса', 'Открылось заявление на экспертизу для включения в КНФ', 3600);
  });

  await card('Портал МЗ РК', 'Государственные услуги для бизнеса',
    'Категории, поиск в пределах категории, внешние услуги и услуга кабинета, выбор вида композитной услуги. Адаптировано под ноутбуки, мониторы 24–27″, планшеты и телефоны.', 5200);
}
