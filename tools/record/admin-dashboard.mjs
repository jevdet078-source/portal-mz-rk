/**
 * Видео «Дашборд мониторинга пользователей» — постановки аналитика от 12.11.2026
 * («Дашборд админ панель» и «Разработка UI/UX-дизайна дашборда мониторинга панели администратора»).
 *
 *   npm run record -- admin-dashboard --voice --tts=edge --no-subs
 *     → exports/video/29. Дашборд мониторинга пользователей.mp4
 *
 * Переключение на роль администратора → карточки → «требуют внимания» → профили → динамика →
 * таблица и организации → фильтры (связь профиля и субъекта, «Применить», подсветка) → период →
 * состояния загрузки, пустых данных и ошибок.
 */

export const title = 'Дашборд мониторинга пользователей';
export const fileName = '29. Дашборд мониторинга пользователей';
export const start = 'Кабинет бизнеса.dc.html';
export const voice = true;

export default async function record(ctx) {
  const { page, sleep, say, title: card, click, point, at, waitText, section } = ctx;

  /** Навести настоящую мышь (подсказки и hover-состояния) — n-й элемент по селектору */
  const hover = async (sel, idx = 0, wait = 900) => {
    const box = await page.evaluate(([s, i]) => {
      const el = document.querySelectorAll(s)[i];
      if (!el) return null;
      const r = el.getBoundingClientRect();
      return { x: Math.round(r.left + r.width / 2), y: Math.round(r.top + r.height / 2) };
    }, [sel, idx]).catch(() => null);
    if (!box) return;
    await at(box.x, box.y);
    await sleep(450);
    try { await page.mouse.move(box.x, box.y, { steps: 8 }); } catch (e) {}
    await sleep(wait);
  };
  /** Увести мышь в пустое место, чтобы подсказка не висела в следующем кадре */
  const away = async () => { try { await page.mouse.move(1430, 150, { steps: 4 }); } catch (e) {} await sleep(200); };
  /** Плавно прокрутить так, чтобы блок оказался под шапкой */
  const scrollTo = async (sel, offset = 92) => {
    await away();
    await page.evaluate(([s, o]) => {
      if (s === 'top') { window.scrollTo({ top: 0, behavior: 'smooth' }); return; }
      const el = document.querySelector(s);
      if (!el) return;
      window.scrollTo({ top: Math.max(0, el.getBoundingClientRect().top + scrollY - o), behavior: 'smooth' });
    }, [sel, offset]).catch(() => {});
    await sleep(900);
  };
  const pick = async (trigger, option) => {
    await click('', trigger);
    await sleep(500);
    await click(option, '.pop .opt');
    await sleep(400);
  };
  const demo = async (...labels) => {
    for (const l of labels) { await click(l, '[aria-pressed]'); await sleep(350); }
  };

  await card('Портал МЗ РК · кабинет бизнеса', 'Дашборд мониторинга пользователей',
    'Панель администратора: учётные записи, профили, динамика регистрации и организации.', 5200,
    'Дашборд мониторинга пользователей. Панель администратора: учётные записи, профили, динамика регистрации и организации.');

  // ── 1. Вход в раздел ──────────────────────────────────────────────
  await section('роль', async () => {
    await say('Роль администратора', 'Дашборд доступен в роли «Администратор» — переключатель в шапке кабинета', 3200,
      'Дашборд доступен в роли администратора. Роль переключается в шапке кабинета бизнеса.');
    await click('', 'button[title="Организация и роль"]');
    await sleep(900);
    await click('Администратор', '[role=menuitemradio]');
    await waitText('Всего пользователей', 15000);
    await sleep(1800);
    await point('Дашборд', 'a.bn-it');
    await say('Раздел «Дашборд»', 'Первый пункт группы «Администрирование», открывается сразу после смены роли', 3200,
      'После смены роли сразу открывается дашборд. Это первый пункт в группе администрирование.');
    await point('Пользователи', '[role=tab]');
    await say('Вкладки', '«Пользователи» — мониторинг пользователей; «Заявки» и «Статистическая отчётность» в разработке', 3200,
      'Сейчас работает вкладка пользователи. Заявки и статистическая отчётность появятся позже.');
  });

  // ── 2. Карточки ───────────────────────────────────────────────────
  await section('карточки', async () => {
    await point('Всего пользователей', '.kpi');
    await say('Общие показатели', 'Учётные записи: всего, активные, деактивированные и удалённые — с долей от общего числа', 3400,
      'Четыре карточки показывают учётные записи: всего, активные, деактивированные и удалённые, с долей от общего числа.');
    await hover('.kpi .info', 0, 1200);
    await say('Подсказка', 'Текущее состояние базы, без учёта периода; пользователь с несколькими профилями — один раз', 3400,
      'Это текущее состояние всей базы, период регистрации на карточки не влияет. Пользователь с несколькими профилями учитывается один раз.');
    await away();
    await hover('.kpi', 2, 700);
    await say('Переход', 'Карточка открывает раздел «Пользователи» на нужной вкладке', 2800,
      'Каждая карточка открывает раздел пользователи сразу на нужной вкладке.');
    await away();
  });

  // ── 3. Требуют внимания ───────────────────────────────────────────
  await section('внимание', async () => {
    await point('деактивированы', '[role=status]');
    await say('Требуют внимания', 'Профили, деактивированные вместе с удалённой организацией, — отдельно и другим цветом', 3600,
      'Оранжевая плашка отделяет то, что требует внимания: профили, деактивированные вместе с удалённой организацией. Кнопка посмотреть ведёт к этим пользователям.');
  });

  // ── 4. Профили ────────────────────────────────────────────────────
  await section('профили', async () => {
    await scrollTo('.db-r2');
    await point('Пользователи по профилям', 'h2');
    await say('Пользователи по профилям', 'Полоса — доли пяти профилей, строки — число пользователей и процент', 3400,
      'Распределение по профилям. Полоса показывает доли, а строки — число пользователей и процент.');
    await hover('.prow', 1, 900);
    await say('Бизнес', 'Наведение выделяет профиль; у «Бизнеса» — разбивка на ИП и ЮЛ', 3000,
      'При наведении профиль выделяется. У бизнеса отдельно индивидуальные предприниматели и юридические лица.');
    await hover('#db-t-prof + .info', 0, 1200);
    await say('Почему сумма больше', 'Пользователь учитывается в каждом своём профиле', 2800,
      'Пользователь учитывается в каждом своём профиле, поэтому сумма больше общего числа. Пояснение — в подсказке.');
    await away();
  });

  // ── 5. Динамика ───────────────────────────────────────────────────
  await section('динамика', async () => {
    await point('Динамика регистрации', 'h2');
    await hover('[data-tip^="Предыдущий"]', 0, 1200);
    await say('Новые за период', 'Сколько зарегистрировалось и сравнение с предыдущим периодом той же длины', 3600,
      'Динамика регистрации: сколько новых пользователей за период и как это отличается от предыдущего периода такой же длины.');
    await away();
    await hover('.bk', 9, 900);
    await say('Столбец', 'Число регистраций и изменение к прошлому месяцу', 2800,
      'При наведении на столбец видно число регистраций и изменение к прошлому месяцу.');
    await hover('.bk', 10, 900);
    await say('Текущий месяц', 'Месяц ещё не завершён — столбец светлее', 2600,
      'Текущий месяц ещё не завершён, поэтому столбец светлее.');
    await away();
  });

  // ── 6. Таблица и организации ──────────────────────────────────────
  await section('таблица', async () => {
    await scrollTo('.db-r3');
    await point('Пользователи по профилям и статусам', 'h2');
    await say('Профили по статусам', 'Активные, деактивированные и удалённые профили по каждому типу, внизу — итог', 3400,
      'Таблица считает профили по статусам для каждого типа. Внизу итог.');
    await hover('.hint', 0, 1300);
    await say('«Прочие»', 'Появляется, только если есть профили с нестандартным статусом, — требуют проверки', 3400,
      'Столбец прочие появляется, только если есть профили с нестандартным статусом. Он выделен как требующий проверки.');
    await away();
    await hover('.org', 0, 900);
    await say('Крупнейшие организации', 'Пятёрка по числу профилей; клик открывает карточку организации, «Все» — реестр', 3600,
      'Крупнейшие организации — пятёрка по числу профилей. Клик открывает карточку организации, ссылка все — весь реестр.');
    await away();
  });

  // ── 7. Фильтры ────────────────────────────────────────────────────
  await section('фильтры', async () => {
    await scrollTo('top');
    await point('Тип профиля', '#db-f-profile');
    await say('Фильтры', 'Одна строка над всеми блоками: период, тип профиля, тип субъекта, статус', 3200,
      'Фильтры собраны в одну строку над всеми блоками: период регистрации, тип профиля, тип субъекта и статус.');
    await pick('#db-f-profile', 'Бизнес');
    await click('', '#db-f-subject');
    await sleep(700);
    await say('Связанные фильтры', 'Для «Бизнеса» остаются только ИП и юридическое лицо — пустых сочетаний не бывает', 3400,
      'Тип субъекта связан с профилем: для бизнеса остаются только индивидуальный предприниматель и юридическое лицо. Пустых сочетаний не бывает.');
    try { await page.keyboard.press('Escape'); } catch (e) {}
    await sleep(400);
    await click('Применить', 'button');
    await sleep(1400);
    await say('«Применить»', 'Карточки, распределение и динамика пересчитаны, график — в цвете профиля', 3200,
      'Фильтры применяются кнопкой применить. Карточки, распределение и динамика пересчитались, а график окрасился в цвет профиля.');
    await pick('#db-f-status', 'Деактивированные');
    await click('Применить', 'button');
    await sleep(1400);
    await scrollTo('.db-r3');
    await say('Подсветка', 'Выбранные профиль и статус подсвечены, остальное приглушено — контекст не теряется', 3600,
      'В таблице и распределении выбранные профиль и статус подсвечены, остальное приглушено. Контекст не теряется. Организации — с деактивированными профилями.');
  });

  // ── 8. Период ─────────────────────────────────────────────────────
  await section('период', async () => {
    await scrollTo('top');
    await click('', '#db-f-period');
    await sleep(700);
    await say('Период регистрации', 'Готовые периоды или свой — две даты', 2800,
      'Период регистрации: готовые варианты или свой, по двум датам.');
    await click('Последние 30 дней', '.pop .opt');
    await sleep(400);
    await click('Применить', 'button');
    await sleep(1400);
    await scrollTo('.db-r2');
    await hover('.bk', 25, 900);
    await say('Шаг графика', 'Короткий период — по дням, до четырёх месяцев — по неделям, дальше — по месяцам', 3400,
      'Шаг графика подстраивается под период: короткий — по дням, до четырёх месяцев — по неделям, дальше — по месяцам.');
    await away();
    await scrollTo('top');
    await click('Сбросить', 'button');
    await sleep(1300);
    await say('«Сбросить»', 'Все фильтры возвращаются к исходным', 2400,
      'Кнопка сбросить возвращает все фильтры к исходным.');
  });

  // ── 9. Состояния ──────────────────────────────────────────────────
  await section('состояния', async () => {
    await click('Прототип', 'button');
    await sleep(600);
    await demo('Загрузка');
    await say('Загрузка', 'Каркас блоков на своих местах — без скачков страницы', 2800,
      'Пока данные загружаются, на месте блоков их каркас, страница не прыгает.');
    await demo('Норма', 'Нет данных');
    await sleep(500);
    await say('Нет данных', 'Нули в карточках и пустые состояния в блоках', 2800,
      'Если данных нет, в карточках нули, а в блоках — пустые состояния.');
    await demo('Есть данные', 'Сбой блока');
    await sleep(500);
    await say('Сбой одного блока', 'Ошибка только там, где не ответил сервис, — с кнопкой «Повторить»', 3200,
      'Если не ответил один сервис, ошибка показывается только в его блоке, с кнопкой повторить.');
    await demo('Сбой API');
    await sleep(500);
    await say('Сбой всех данных', 'Одно сообщение вместо пустой страницы и «Повторить»', 2800,
      'Если недоступно всё, одно понятное сообщение и кнопка повторить.');
    await demo('Норма');
    await click('Прототип', 'button');
    await sleep(1200);
    await say('Итог', 'Дашборд мониторинга пользователей — по постановке, на ноутбуках и больших мониторах', 3200,
      'Дашборд мониторинга пользователей готов. Он одинаково аккуратно выглядит на ноутбуках и больших мониторах.');
  });
}
