/**
 * Видео «Кабинет гражданина — ЭПЗ»: разделы «Просмотр ЭПЗ» и «Управление доступами к ЭПЗ»
 * по постановке «Добавление разделов „ЭПЗ“ и „Управление доступами к ЭПЗ“ в ЛК гражданина».
 *
 *   npm run record -- citizen-epz   → exports/video/20. Кабинет гражданина — ЭПЗ.mp4
 *
 * Меню кабинета, просмотр своего ЭПЗ (без ИИН и КДП) по разделам, затем управление доступами:
 * общий запрет, выбор разделов, «Выбрать все» / «Снять все», несохранённые изменения, сохранение, отмена.
 */

export const title = 'Кабинет гражданина — ЭПЗ';
export const fileName = '20. Кабинет гражданина — ЭПЗ';
export const start = 'Личный кабинет.dc.html';
// самый частый размер ноутбука (1920×1080 при масштабе 125 %)
export const viewport = { width: 1536, height: 864 };

export default async function record(ctx) {
  const { page, sleep, say, title: card, click, point, show, waitText, open, section } = ctx;
  const top = () => page.evaluate(() => window.scrollTo({ top: 0, behavior: 'smooth' })).then(() => sleep(700));
  const epz = async (label, head, text, ms) => {
    await click(label, '.epz-nav-btn');
    await sleep(700);
    await say(head || label, text, ms);
  };

  await card('Портал МЗ РК · личный кабинет гражданина', 'Электронный паспорт здоровья',
    'Два новых раздела кабинета: просмотр своего ЭПЗ и управление доступом медицинского персонала к нему.', 5200);

  await section('меню кабинета', async () => {
    await open('Личный кабинет.dc.html');
    await page.evaluate(() => localStorage.removeItem('mp-epz-access'));
    await point('Электронный паспорт', '.cn-grp');
    await say('Меню кабинета', 'Новый пункт «Электронный паспорт здоровья (ЭПЗ)» с двумя подразделами', 3600);
    await click('Электронный паспорт', '.cn-grp');
    await sleep(500);
    await say('Подразделы', '«Просмотр ЭПЗ» и «Управление доступами к ЭПЗ»', 3000);
    await click('Просмотр ЭПЗ', '.cn-sub a');
    await waitText('Группа крови', 15000);
    await sleep(700);
  });

  await section('просмотр ЭПЗ', async () => {
    await point('Просмотр ЭПЗ', '.cn-sub a');
    await say('Просмотр ЭПЗ', 'Выбранный подраздел выделен. ЭПЗ открыт сразу — без ввода ИИН и запроса доступа', 4200);
    await point('Главная', '.epz-nav-btn');
    await say('Разделы ЭПЗ', 'Те же разделы, навигация и оформление, что в кабинете медицинского персонала', 4000);
    await point('Группа крови', '.epz-lbl');
    await say('Главная', 'Персональные данные, основные показатели, лекарственная аллергия и прикрепление', 4000);
    await epz('Амбулаторная помощь', '', 'Все приёмы — таблица растягивается на ширину экрана, без горизонтальной прокрутки', 4000);
    await epz('Заболевания', '', 'Реестр установленных диагнозов', 3000);
    await epz('Аллергологический анамнез', '', 'Аллергены, характер реакции и тяжесть', 3000);
    await epz('Профилактика', '', 'Скрининги и вакцинация', 2800);
    await epz('Женское здоровье', 'Беременность', 'Ведение беременности: срок, скрининги, визиты', 3200);
    await top();
    await epz('Вызовы скорой', '', 'История вызовов скорой медицинской помощи', 3000);
    await epz('Больничные и справки', 'Медицинские документы', 'Листы нетрудоспособности и справки', 3000);
    await top();
  });

  await section('доступы: запрет', async () => {
    await click('Управление доступами к ЭПЗ', '.cn-sub a');
    await waitText('Разделы ЭПЗ', 15000);
    await sleep(800);
    await point('Не предоставлять доступ к ЭПЗ', '#ac-ban-lbl');
    await say('Общий запрет', '«Не предоставлять доступ к ЭПЗ» — установлен по умолчанию', 3400);
    await point('', '.ac-ban .ac-info');
    await sleep(700);
    await say('Подсказка', 'Пояснения — в подсказках, чтобы не перегружать экран', 3200);
    await point('', '.ac-perm [data-tip]');
    await sleep(700);
    await say('Разделы недоступны', 'Пока действует общий запрет, разделы сняты и не выбираются', 3600);
  });

  await section('доступы: выбор разделов', async () => {
    await click('', '.ac-ban .ac-chk');
    await sleep(600);
    await say('Запрет снят', 'Теперь разделы можно выбирать', 2600);
    await click('Общие сведения', '.ac-row');
    await click('Аллергологический анамнез', '.ac-row');
    await click('Вакцинация', '.ac-row');
    await sleep(400);
    await say('Разрешить просмотр врачу', 'Разрешённый раздел — цветной значок и «Разрешён», запрещённый — серый', 3800);
    await point('Изменения не сохранены', '.ac-save-st');
    await say('Несохранённые изменения', 'Изменённые строки отмечены точкой, внизу — «Изменения не сохранены»', 4000);
    await point('Разрешено 3 из 11', '.ac-count');
    await say('Счётчик', 'Сколько разделов открыто врачу', 2400);
  });

  await section('доступы: массовые действия и сохранение', async () => {
    await click('Выбрать все', '.ac-btn');
    await sleep(600);
    await say('Выбрать все', 'Разрешает просмотр всех разделов и снимает общий запрет', 3400);
    await click('Беременность', '.ac-row');
    await sleep(400);
    await say('По одному', 'Отдельный раздел можно закрыть одним нажатием', 2800);
    await click('Сохранить настройки доступа', '.ac-btn');
    await waitText('Настройки доступа успешно сохранены', 5000);
    await say('Сохранено', 'Уведомление «Настройки доступа успешно сохранены»', 3200);
  });

  await section('доступы: снять все и отмена', async () => {
    await click('Снять все', '.ac-btn');
    await sleep(600);
    await say('Снять все', 'Снимает все разрешения и включает общий запрет', 3200);
    await click('Отмена', '.ac-btn');
    await sleep(700);
    await say('Отмена', 'Возвращает последние сохранённые настройки', 3000);
  });

  await card('Портал МЗ РК', 'Электронный паспорт здоровья', 'Интерфейс растягивается по ширине экрана — от ноутбука до монитора 27″, работает на планшетах и телефонах.', 4600);
}
