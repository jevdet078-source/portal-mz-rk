/**
 * Видео «Профиль врача — согласие и обновление» — доработки по новой редакции
 * постановки UC1.1 «Реализация профиля медперсонала».
 *
 *   npm run record -- doctor-profile-consent   → exports/video/9. Профиль врача — согласие и обновление.mp4
 *
 * Этап 1 (при регистрации — только места работы), этап 2 (кнопка «Обновить»,
 * согласие по SMS с номера 1414, push-уведомление), счётчик «Повторно через 01:59»,
 * все места работы, новые поля, новые сообщения §7 и то, что убрано как не входящее в постановку.
 * Только изменения этой доработки.
 */

export const title = 'Профиль врача — согласие и обновление';
export const fileName = '9. Профиль врача — согласие и обновление';
export const start = 'Профиль врача.dc.html';

export default async function record(ctx) {
  const { page, sleep, say, title: card, click, point, show, waitText, open, section } = ctx;

  const PANEL = 'Прототип · сценарии';
  async function pick(...labels) {
    await click(PANEL, '.pf-pp > button');
    await sleep(400);
    for (const label of labels) { await click(label, '.pf-pp .pp-btn'); await sleep(250); }
    await click(PANEL, '.pf-pp > button');
    await sleep(300);
  }
  const top = () => page.evaluate(() => window.scrollTo({ top: 0, behavior: 'smooth' })).then(() => sleep(700));
  const tab = async (name) => { await click(name, '[role=tab]'); await sleep(500); };
  const refresh = () => click('Обновить', '.pf-sync button');

  await card('Портал МЗ РК · кабинет медработника', 'Профиль врача — согласие и обновление',
    'Доработки по новой редакции постановки UC1.1: два этапа загрузки сведений из СУР.', 5200);

  await section('открытие', async () => {
    await open('Профиль врача.dc.html');
    await page.evaluate(() => {
      ['mp-doc-sur', 'mp-doc-sur-refresh', 'mp-doc-photo'].forEach((k) => localStorage.removeItem(k));
      sessionStorage.removeItem('mp-sur-scn'); sessionStorage.removeItem('mp-kdp-scn');
    });
    await open('Профиль врача.dc.html');
    await waitText('Обновлено сегодня', 15000);
    await sleep(600);
  });

  // ── 1. Этап 1 ─────────────────────────────────────────────────────
  await section('этап 1', async () => {
    await card('Этап 1', 'Профиль после регистрации', 'При регистрации из СУР загружаются только места работы.');
    await show('Городская поликлиника № 4', 'h3', 'start');
    await say('Места работы', 'Теперь показываются все места работы, а не только текущие', 3600);
    await point('Состояние должности', '.pf-dt');
    await say('Новое поле', 'Добавлено «Состояние должности»', 2600);
    await page.evaluate(() => window.scrollTo({ top: document.body.scrollHeight, behavior: 'smooth' }));
    await sleep(900);
    await point('Уволен', '.pf-badge');
    await say('Уволен', 'Прежнее место работы — с серым бейджем «Уволен» и датой увольнения', 3600);
    await top();
    await tab('Квалификация');
    await say('До согласия', '«Данные будут доступны после подтверждения согласия. Нажмите «Обновить».»', 4000);
    await point('Обновить', '.pf-sync button');
    await say('Обновить', 'Пока согласия нет, кнопка выделена — это следующий шаг врача', 3200);
  });

  // ── 2. Этап 2 ─────────────────────────────────────────────────────
  await section('этап 2', async () => {
    await card('Этап 2', 'Согласие по SMS', 'После «Обновить» врачу приходит SMS с номера 1414.');
    await refresh();
    await waitText('направлено SMS-сообщение', 5000);
    await sleep(500);
    await point('направлено SMS-сообщение', '.pf-push');
    await say('Push-уведомление', 'Текст из постановки: ответьте на SMS, чтобы подтвердить согласие', 3800);
    await point('Повторно через', '.pf-sync button');
    await say('Счётчик', 'Кнопка неактивна 2 минуты: «Повторно через 01:59». Счётчик не сбрасывается при перезагрузке', 4400);
    await waitText('Регистрационный номер', 12000);
    await sleep(500);
    await say('Ответ «Да»', 'Получен kdpToken: загружены квалификация, образование и трудовая деятельность', 4000);
    await show('Кардиология', 'h3', 'start');
    await say('Квалификация', 'Добавлено «Наименование документа». Срок «осталось N лет» и плашка об окончании сертификата убраны — их нет в постановке', 5200);
    await top();
    await tab('Трудовая деятельность');
    await say('Трудовая деятельность', 'Только поля постановки: должность, специальность, период. Стаж и длительности убраны', 4200);
    await point('Обновлено сегодня', '.pf-sync');
    await say('Обновлено', 'Время меняется только после успешного получения данных', 3200);
  });

  // ── 3. Ошибки ─────────────────────────────────────────────────────
  async function scenario(name, labels, wait, text, ms = 3600) {
    await section(name, async () => {
      await top();
      await pick(...labels, 'Сбросить счётчик');
      await refresh();
      await waitText(wait, 12000);
      await sleep(500);
      await say(name, text, ms);
    });
  }

  await card('Исключения', 'Ошибки и отказ', 'Ранее загруженные данные не удаляются, если обновление не удалось.');
  await scenario('Ответ «Нет»', ['Ответ на SMS «Нет»'], 'Согласие не подтверждено', '«Согласие не подтверждено. Данные не обновлены.» Данные остаются на месте', 4000);
  await scenario('Номер не найден', ['Номер не найден в БМГ'], 'Не найден номер телефона', 'Номера нет в Базе мобильных граждан — сообщение из постановки', 3600);
  await scenario('КДП недоступен', ['KDP_SERVICE недоступен'], 'Не удалось отправить запрос', '«Не удалось отправить запрос на согласие. Повторите попытку позже.»', 3800);
  await scenario('СУР недоступен', ['Ответ на SMS «Да»', 'СУР недоступен'], 'Не удалось загрузить данные профиля', 'Теперь сообщением над вкладками: профиль не блокируется, данные остаются', 3800);
  await scenario('Нет данных по ИИН', ['Нет данных по ИИН'], 'не найдены в СУР', 'Информационное сообщение, ранее загруженные данные сохраняются', 3400);

  await card('Портал МЗ РК', 'Профиль врача — согласие и обновление', 'Всё по постановке UC1.1. Работает и на планшетах, и на телефонах.', 4400);
}
