/**
 * Видео «Администрирование — пользователи и полномочия» — по постановке аналитика.
 *
 *   npm run record -- admin-users   → exports/video/4. Администрирование — пользователи.mp4
 *
 * Реестр и поиск; создание с ГБД ФЛ/ЮЛ и каскадом профиль → уровень → роль;
 * проверки (Alt 1, 3, 4) и дубликат (Alt 2); редактирование; удаление с отменой (Alt 5);
 * деактивированные и восстановление (Alt 6).
 */

export const title = 'Администрирование — пользователи';
export const fileName = '4. Администрирование — пользователи';
export const start = 'Пользователи.dc.html';

/** Субтитр уходит левее открытой панели, тост — выше субтитра */
export const LAYOUT_CSS = [
  'body:has(#am-drawer) #demo-caption{left:calc((100vw - 640px) / 2) !important;width:760px !important}',
  'div[role=status]{bottom:150px !important}',
].join('');

export default async function record(ctx) {
  const { page, sleep, caption, say, title: card, click, point, show, type, clearField, waitText, open, section } = ctx;
  const layout = () => page.addStyleTag({ content: LAYOUT_CSS }).catch(() => {});
  const go = async (path) => { await open(path); await layout(); };
  const pick = async (trigger, option) => { await click('', trigger); await sleep(400); await click(option, '[role=option]'); await sleep(500); };
  /** Найти запись поиском: после создания реестр стоит на странице новой записи */
  const find = async (q) => { await clearField('#am-search'); await type('#am-search', q, 90); await sleep(500); };

  await layout();
  await card('Портал МЗ РК · кабинет бизнеса', 'Пользователи и полномочия',
    'Администратор ведёт учётные записи: профиль, организация, уровень и роль определяют доступ к функционалу портала.', 5200);

  // ── 1. Реестр ─────────────────────────────────────────────────────
  await section('реестр', async () => {
    await say('Раздел «Администрирование»', 'Пункт виден только в роли «Администратор». Заявитель его не видит, а при прямом заходе получает экран-заглушку', 4200);
    await point('Действующие', '[role=tab]');
    await say('Вкладки статусов', 'Действующие, Деактивированные, Удалённые — со счётчиками. По умолчанию открыты «Действующие»');
    await point('', '[role=table] [role=row]');
    await say('Таблица', 'ФИО и ИИН, организация и БИН, почта, тип и профиль, уровень и роль — все столбцы постановки в пяти колонках, без горизонтальной прокрутки', 4600);
    await type('#am-search', 'ннцрз', 140);
    await sleep(600);
    await say('Поиск', 'Мгновенный — по ИИН, имени, фамилии, почте и организации. Понимает и аббревиатуры: ННЦРЗ, КМФК, НЦЭЛС');
    await pick('#flt-role', 'Председатель формулярной комиссии');
    await say('Фильтры', 'Тип, профиль, уровень и роль. Списки связаны: при выбранном профиле предлагаются только его уровни и роли');
    await click('Сбросить', 'button');
    await say('«Сбросить»', 'Очищает поиск и фильтры и возвращает полный список вкладки');
  });

  // ── 2. Создание ───────────────────────────────────────────────────
  await section('создание', async () => {
    await card('Сценарий 1', 'Новый пользователь', 'Сотрудник госоргана: ФИО — из ГБД ФЛ, организация — из реестра портала, уровень подбирается по БИН.');
    await click('Новый пользователь', 'button');
    await sleep(600);
    await say('Боковая панель', 'Форма открывается сбоку — реестр остаётся на виду. Шаги идут от общего к частному');
    await click('Юрлицо', '[role=radio]');
    await say('Шаг 1 · Тип пользователя', 'ФЛ, ИП или ЮЛ. От типа зависят поля организации и доступные профили');
    await type('#uf-iin', '940815400345');
    await waitText('ФИО получены из ГБД ФЛ');
    await sleep(500);
    await say('ИИН → ГБД ФЛ', 'После 12 цифр — запрос в ГБД ФЛ. Фамилия, имя и отчество заполняются сами и не редактируются');
    await type('#uf-bin', '110340017483');
    await waitText('Организация есть в реестре портала');
    await sleep(400);
    await say('Шаг 2 · Организация', 'БИН ищется в реестре портала, затем в ГБД ЮЛ или ИС КГД для ИП. Наименование подставляется');
    await type('#uf-position', 'Главный эксперт', 60);
    await type('#uf-email', 'a.sarsenova@nncrz.kz', 50);
    await type('#uf-phone', '7012345678', 90);
    await say('Шаг 3 · Контакты', 'Почта проверяется по формату, телефон сам приводится к виду +7 XXX XXX XX XX');
    await pick('#uf-profile', 'Госорган');
    await say('Шаг 4 · Профиль → уровень', 'Уровень «Госорган · ННЦРЗ» выбран автоматически по БИН. Уровни других госорганов для этой организации недоступны', 4400);
    await pick('#uf-role', 'Специалист по профессиональной экспертизе');
    await show('Полномочия роли', 'div');
    await say('Роль и полномочия', 'Роли — только этого уровня. Под ролью видно, какие полномочия она выдаёт');
    await click('Сохранить', '#am-drawer button');
    await sleep(900);
    await say('Alt 1 · Ошибки заполнения', 'Незаполненные поля подсвечены, вверху — сколько полей исправить, курсор переведён на первое. Сохранения нет', 4400);
    await type('#uf-pass', 'qwerty12', 110);
    await type('#uf-pass2', 'qwerty13', 110);
    await page.evaluate(() => document.getElementById('uf-pass2').blur());
    await sleep(500);
    await say('Alt 3 и Alt 4 · Пароль', 'Тексты по постановке: требования к паролю и «Пароли не совпадают». Чипы показывают, какого правила не хватает', 4600);
    await click('Сгенерировать', 'button');
    await say('Генератор пароля', 'Надёжный пароль по всем правилам — сразу в оба поля и видимым, чтобы передать пользователю');
    await click('Сохранить', '#am-drawer button');
    await waitText('Пользователь создан');
    await sleep(500);
    await say('Пользователь создан', 'Запись появилась во вкладке «Действующие» — строка подсвечена на нужной странице реестра');
  });

  // ── 3. Дубликат ───────────────────────────────────────────────────
  await section('дубликат', async () => {
    await card('Сценарий 2 · Alt 2', 'Пользователь уже существует', 'Уникальность — ИИН + БИН + тип + профиль + уровень.');
    await click('Новый пользователь', 'button');
    await sleep(500);
    await click('Физлицо', '[role=radio]');
    await type('#uf-iin', '010509550711');
    await waitText('ФИО получены из ГБД ФЛ');
    await type('#uf-email', 'test@mail.kz', 50);
    await type('#uf-phone', '7015551234', 70);
    await say('Каскад', 'Для физлица доступен один профиль — «Гражданин», и один уровень — «Заявитель». Выбраны автоматически');
    await pick('#uf-role', 'Специалист с правом подписи');
    await click('Сгенерировать', 'button');
    await click('Сохранить', '#am-drawer button');
    await waitText('уже зарегистрирован');
    await sleep(600);
    await say('Сообщение по постановке', '«Пользователь с указанными данными уже зарегистрирован.» Создание не выполняется, запись можно открыть', 4400);
    await click('Отмена', '#am-drawer button');
    await sleep(500);
    await say('Защита от потери данных', 'Форма заполнена — перед закрытием система спрашивает подтверждение');
    await click('Закрыть без сохранения', '#am-confirm button');
  });

  // ── 4. Редактирование ─────────────────────────────────────────────
  await section('редактирование', async () => {
    await card('Сценарий 3', 'Редактирование', 'Данные из ГБД — только просмотр. Меняются почта, телефон, уровень, роль и пароль.');
    await find('Искаков');
    await click('Искаков', 'button.name-btn');
    await sleep(700);
    await say('Карточка', 'Тип, профиль, ИИН, ФИО, БИН и организация — только для чтения. Внизу — другие профили этого ИИН', 4200);
    await clearField('#uf-email');
    await type('#uf-email', 'e.iskakov@nncrz.gov.kz', 45);
    await point('Задать новый пароль', 'button');
    await say('Пароль', 'Не меняется, пока администратор явно не нажмёт «Задать новый пароль»');
    await click('Сохранить', '#am-drawer button');
    await waitText('Изменения сохранены');
    await say('Сохранено', 'Уведомление перечисляет, что именно изменилось');
  });

  // ── 5. Удаление ───────────────────────────────────────────────────
  await section('удаление', async () => {
    await card('Сценарий 4', 'Удаление пользователя', 'Подтверждение, отмена (Alt 5) и возврат из уведомления.');
    await find('Ким');
    await click('', 'button[aria-label^="Удалить: Ким"]');
    await sleep(600);
    await say('Подтверждение', '«Вы уверены, что хотите удалить пользователя?» — с карточкой, чтобы не ошибиться записью. «Отмена» ничего не меняет', 4400);
    await click('Удалить', '#am-confirm button.btn-d');
    await waitText('Пользователь удалён');
    await say('Удалено', 'Запись перешла во «Удалённые», вход закрыт. Ошибку можно исправить сразу — «Отменить» в уведомлении');
    await click('Отменить', 'div[role=status] button');
    await sleep(900);
    await say('Отменено', 'Пользователь вернулся в «Действующие» — строка подсвечена');
  });

  // ── 6. Деактивированные и удалённые ───────────────────────────────
  await section('восстановление', async () => {
    await card('Сценарий 5 · Alt 6', 'Деактивированные и удалённые', 'Просмотр и восстановление.');
    await clearField('#am-search');
    await click('', '#am-tab-inactive');
    await sleep(500);
    await say('Деактивированные', 'Сюда автоматически попадают пользователи организаций, удалённых из реестра');
    await click('Галиев', 'button.name-btn');
    await sleep(700);
    await say('Просмотр', 'Все поля только для чтения, пароль скрыт. Причина — организация удалена; восстановить можно после её восстановления', 4600);
    await click('Закрыть', '#am-drawer button');
    await click('', '#am-tab-deleted');
    await sleep(500);
    await click('', 'button[aria-label^="Восстановить: Серикбаева"]');
    await sleep(600);
    await say('Восстановление', '«Вы действительно хотите восстановить пользователя?» — после подтверждения запись вернётся в «Действующие»', 4200);
    await click('Восстановить', '#am-confirm button.btn-p');
    await waitText('Пользователь восстановлен');
    await say('Восстановлено', 'С прежними профилем, уровнем и ролью. Страница и поиск после операций сохраняются');
  });

  await card('Портал МЗ РК · кабинет бизнеса', 'Пользователи и полномочия',
    'Далее — реестр организаций: удаление организации автоматически деактивирует её пользователей.', 4200);
}
