/**
 * Видео «Администрирование отчётности — доработки» — только то, что поменялось по замечаниям
 * аналитика после тестирования (08.11.2026): левое меню разделов, редактирование назначений,
 * проверка повторных назначений и каталог из 28 форм, журнал — заглушка.
 *
 *   npm run record -- org-reports-remarks --voice --tts=edge --no-subs
 *     → exports/video/27. Администрирование отчётности — доработки.mp4
 */

export const title = 'Администрирование отчётности — доработки';
export const fileName = '27. Администрирование отчётности — доработки';
export const start = 'Вход.dc.html';
export const voice = true;

/** Уведомления — справа внизу, чтобы не перекрывать кнопки панели */
const LAYOUT_CSS = '.ad-toast{left:auto !important;right:24px !important;bottom:24px !important;transform:none !important}';

export default async function record(ctx) {
  const { page, sleep, say, title: card, click, point, type, waitText, section } = ctx;
  const layout = () => page.addStyleTag({ content: LAYOUT_CSS }).catch(() => {});
  const demo = async (text) => {
    await click('Показ прототипа', '.ad-demo-btn');
    await sleep(500);
    await click(text, '.ad-demo .ad-opt');
    await sleep(1400);
  };
  const pickEmp = async (q, name) => {
    await click('', '#ad-emp');
    await sleep(500);
    await type('.ad-dr .ad-ms input', q, 110);
    await sleep(400);
    await click(name, '.ad-dr .ad-opt');
    await sleep(400);
  };
  const pickRole = async (name) => {
    await click('', '#ad-role');
    await sleep(500);
    await click(name, '.ad-dr .ad-menu .ad-opt');
    await sleep(500);
  };

  await card('Портал МЗ РК · замечания аналитика', 'Администрирование отчётности — доработки',
    'Левое меню, редактирование назначений, перечень форм, журнал.', 5000,
    'Администрирование отчётности. Доработки по замечаниям аналитика.');

  // ── Вход ──────────────────────────────────────────────────────────
  await section('вход', async () => {
    await click('Войти с ЭЦП', 'button');
    await sleep(800);
    await click('Жакупова', '.ecp-item');
    await waitText('Введите пароль', 15000);
    await sleep(500);
    await say('Вход', 'Руководитель входит ключом ЭЦП организации', 2600,
      'Первый руководитель входит ключом электронной подписи организации.');
    await type('#login-pass', 'Demo#2026', 90);
    await click('Войти', 'form button[type=submit]');
    await waitText('Выбор отчётных форм', 20000);
    await sleep(1500);
    await layout();
  });

  // ── 1. Левое меню ─────────────────────────────────────────────────
  await section('левое меню', async () => {
    await card('Замечание 1', 'Разделы — в левом меню', 'Журнал отчётных форм и администрирование.', 3000,
      'Первое замечание. Разделы перенесены в левое меню.');
    await point('Журнал отчётных форм', '.rn-it');
    await say('Левое меню', 'Разделы «Журнал отчётных форм» и «Администрирование» — в левом меню', 3400,
      'Журнал отчётных форм и администрирование теперь в левом меню.');
    await point('Администрирование', '.rn-it');
    await say('Активный раздел', 'Открытый раздел выделен, его содержимое — в рабочей области справа', 3400,
      'Открытый раздел выделен, а его содержимое показано в рабочей области справа.');
    await point('Организация', '.rn-c');
    await say('Организация и руководитель', 'Над меню — организация и первый руководитель', 2800,
      'Над меню — организация и первый руководитель.');
  });

  // ── 2. Перечень форм ──────────────────────────────────────────────
  await section('перечень форм', async () => {
    await point('1-ОИПЗ', '.ad-row');
    await say('Перечень форм', '28 форм по списку аналитика: № приложения, индекс и наименование', 3600,
      'Перечень заменён на ваш список: двадцать восемь форм с номером приложения, индексом и наименованием.');
    await demo('Пример настроенной организации');
    await layout();
    await waitText('Добавить назначение', 8000);
    await sleep(600);
    await say('Пример настройки', 'Для показа загрузим организацию с готовыми назначениями', 3000,
      'Для показа загрузим организацию с готовыми назначениями.');
  });

  // ── 3. Редактирование назначения ──────────────────────────────────
  await section('редактирование', async () => {
    await card('Замечание 2', 'Редактирование назначений', 'Снять форму, добавить новые, сохранить или отменить.', 3200,
      'Второе замечание. Редактирование назначений сотрудника.');
    await point('', '#as-s1 .ad-ib:not(.del)');
    await say('Редактировать', 'У каждого назначения — кнопка «Редактировать»', 2800,
      'У каждого назначения появилась кнопка редактировать.');
    await click('', '#as-s1 .ad-ib:not(.del)');
    await sleep(800);
    await layout();
    await say('Окно редактирования', 'Сотрудник, роль и перечень назначенных отчётных форм', 3200,
      'Открывается окно с сотрудником, ролью и перечнем назначенных отчётных форм.');
    await click('6-КФ', '.ad-dr .ad-fo');
    await sleep(700);
    await say('Подтверждение', '«Удалить назначение сотрудника на форму …?» — «Удалить» или «Отмена»', 4200,
      'Снять назначенную форму можно. Сначала подтверждение: удалить назначение сотрудника на эту форму? Удалить или отмена.');
    await click('Удалить', '.ad-mw.up .ad-btn');
    await sleep(700);
    await say('Форма снята', 'Снятая форма зачёркнута до сохранения', 2800,
      'Снятая форма зачёркнута до сохранения.');
    await click('1-ОИПЗ', '.ad-dr .ad-fo');
    await sleep(300);
    await click('3-Вакцины', '.ad-dr .ad-fo');
    await sleep(400);
    await say('Новые формы', 'Добавляются из перечня форм, выбранного для организации', 3000,
      'Новые формы добавляются из перечня, выбранного для организации.');
    await click('Сохранить', '.ad-dr-ft .ad-btn');
    await waitText('Изменения сохранены', 6000);
    await sleep(1000);
    await say('Сохранено', 'Удалено только назначение на снятую форму, остальные назначения сохранены', 3800,
      'Удалено только назначение на снятую форму. Остальные назначения сотрудника и созданные отчёты сохранены.');
  });

  // ── 4. Повторные назначения ───────────────────────────────────────
  await section('повторные назначения', async () => {
    await card('Замечание 3', 'Проверка повторных назначений', 'Одна форма — нескольким сотрудникам.', 3000,
      'Третье замечание. Проверка повторных назначений.');
    await click('Добавить назначение', '.ad-bar .ad-btn');
    await sleep(700);
    await layout();
    await pickEmp('крав', 'Кравченко');
    await pickRole('Исполнитель');
    await point('Уже назначена этому сотруднику', '.ad-fo small');
    await say('Уже назначена', 'Формы, уже назначенные этому сотруднику в этой роли, недоступны', 3800,
      'Формы, уже назначенные этому сотруднику в этой роли, недоступны с пояснением: уже назначена этому сотруднику.');
    await pickEmp('сарс', 'Сарсенбаева');
    await sleep(300);
    await click('6-КФ', '.ad-dr .ad-fo');
    await sleep(300);
    await click('20-МПД', '.ad-dr .ad-fo');
    await sleep(400);
    await say('Несколько сотрудников', 'Одну форму можно назначить нескольким сотрудникам организации', 3400,
      'А другому сотруднику эти же формы доступны. Одну форму можно назначить нескольким сотрудникам организации.');
    await click('Сохранить назначение', '.ad-dr-ft .ad-btn');
    await waitText('Назначение сохранено', 6000);
    await sleep(1200);
  });

  // ── 5. Журнал ─────────────────────────────────────────────────────
  await section('журнал', async () => {
    await card('Замечание 4', 'Журнал отчётных форм', 'Пока заглушка — отдельная постановка.', 3000,
      'Четвёртое замечание. Журнал отчётных форм.');
    await click('Журнал отчётных форм', '.rn-it');
    await waitText('Раздел находится в разработке', 15000);
    await sleep(1200);
    await say('В разработке', 'Название раздела и сообщение «Раздел находится в разработке»', 3400,
      'Пока это заглушка: название раздела и сообщение, что раздел находится в разработке. Функционал журнала будет в отдельной постановке.');
  });

  await card('Готово к проверке', 'Администрирование отчётности — доработки',
    'Вход: ключ «Жакупова Гульмира Сапаровна», пароль Demo#2026.', 4600,
    'Готово к проверке.');
}
