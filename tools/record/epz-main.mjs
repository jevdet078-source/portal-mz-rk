/**
 * Видео «ЭПЗ — главная страница» — оптимизация главной страницы электронной карты
 * пациента по постановке «Оптимизация главной страницы ЭПЗ».
 *
 *   npm run record -- epz-main   → exports/video/11. ЭПЗ — главная страница.mp4
 *
 * Четыре блока главной: персональные данные, основные показатели, предупреждение
 * о лекарственной аллергии (переход в «Аллергологический анамнез»), прикрепление.
 * Затем пациенты с другими данными: умеренная реакция, «Нет данных», только пищевая
 * аллергия, нет записей об аллергии.
 */

export const title = 'ЭПЗ — главная страница';
export const fileName = '11. ЭПЗ — главная страница';
export const start = 'Кабинет врача.dc.html';

export default async function record(ctx) {
  const { page, sleep, say, title: card, click, point, type, clearField, waitText, open, section } = ctx;

  const IIN = 'input[maxlength="12"]';
  async function openPatient(iin) {
    if (await page.$('.epz-back')) {
      await click('', '.epz-back');
      await waitText('Запросить доступ', 5000);
    }
    await clearField(IIN);
    await type(IIN, iin, 60);
    await click('Запросить доступ', 'button');
    await sleep(700);
    await click('Симулировать согласие пациента', 'button');
    await sleep(600);
    await click('Открыть ЭПЗ пациента', 'button');
    await waitText('Участковый врач', 5000);
    await sleep(700);
  }

  await card('Портал МЗ РК · кабинет врача', 'ЭПЗ — главная страница',
    'Главная электронной карты пациента — краткая карточка из четырёх блоков. Подробности — в разделах меню.', 5600);

  await section('открытие ЭПЗ', async () => {
    await open('Кабинет врача.dc.html');
    await openPatient('920512400123');
  });

  await section('четыре блока', async () => {
    await point('Иванова Александра Сергеевна', 'h1');
    await say('Блок 1 · Персональные данные', 'ФИО крупно, под ним в одну строку ИИН, пол, возраст и дата рождения', 4000);
    await point('Группа крови', '.epz-cell');
    await say('Блок 2 · Основные показатели', 'Одна панель с разделителями: группа крови с датой подтверждения, последнее АД с датой измерения', 4400);
    await point('Статус ОСМС', '.epz-cell');
    await say('Статусы', 'Цветом выделены только статусы: ОСМС и беременность', 3400);
    await point('Беременность', '.epz-cell');
    await say('Беременность', 'Показывается только при актуальной записи: статус, срок и триместр', 3600);
    await point('Пенициллин', '.epz-al');
    await say('Блок 3 · Лекарственная аллергия', 'Аллерген, характер реакции и год. Тяжёлая реакция — красным', 4000);
    await point('аллергена', '.epz-al-count');
    await say('Количество аллергенов', 'Всего зарегистрировано аллергенов, включая не лекарственные', 3400);
    await point('Медицинская организация', '.epz-cell');
    await say('Блок 4 · Прикрепление', 'Медицинская организация, участок и участковый врач в одну строку', 3800);
  });

  await section('аллергологический анамнез', async () => {
    await click('Пенициллин', '.epz-al');
    await waitText('Анафилактическая реакция', 5000);
    await sleep(500);
    await say('Переход', 'Нажатие на панель открывает раздел «Аллергологический анамнез» в меню ЭПЗ', 4000);
    await point('Тяжёлая', '.epz-td span');
    await say('Аллергологический анамнез', 'Все зарегистрированные аллергены: тип, характер реакции, тяжесть и год', 4000);
    await click('Главная', '.epz-nav-btn');
    await sleep(600);
    await say('Убрано с главной', 'Диагнозы и Д-учёт, таблица аллергий, план наблюдения, карта беременности, события — остались в разделах меню', 5200);
  });

  await section('другие пациенты', async () => {
    await openPatient('790815300234');
    await point('Ацетилсалициловая кислота', '.epz-al');
    await say('Реакция не тяжёлая', 'Предупреждение остаётся, но без красного цвета. Год не указан — его нет и в тексте', 4400);
    await openPatient('660203301122');
    await point('Нет данных', '.epz-val');
    await say('Нет сведений', 'Если показателя нет — «Нет данных»', 3200);
    await point('Не застрахован', '.epz-val');
    await say('ОСМС', 'Пациент не застрахован — статус красным', 3000);
    await say('Без лекарственной аллергии', 'У пациента только пищевая аллергия — предупреждение на главной не показывается', 4200);
    await openPatient('880920400451');
    await click('Аллергологический анамнез', '.epz-nav-btn');
    await waitText('не зарегистрированы', 5000);
    await sleep(400);
    await say('Записей нет', 'Отсутствие записей не трактуется как подтверждённое отсутствие аллергии', 4200);
  });

  await card('Портал МЗ РК · кабинет врача', 'ЭПЗ — главная страница',
    'Персональные данные, показатели, лекарственная аллергия, прикрепление. Раскладка перестраивается под ширину экрана.', 5200);
}
