/**
 * Видео «Администрирование — организации» — по постановке аналитика.
 *
 *   npm run record -- admin-orgs   → exports/video/5. Администрирование — организации.mp4
 *
 * Реестр и поиск; создание по БИН с проверкой уникальности (Alt 2) и ГБД ЮЛ;
 * карточка; удаление с пользователями (Alt 4) и каскад в «Пользователи»;
 * ошибка транзакции; восстановление.
 */

import { LAYOUT_CSS } from './admin-users.mjs';

export const title = 'Администрирование — организации';
export const fileName = '5. Администрирование — организации';
export const start = 'Организации.dc.html';

export default async function record(ctx) {
  const { page, sleep, caption, say, title: card, click, point, show, type, clearField, waitText, open, section } = ctx;
  const layout = () => page.addStyleTag({ content: LAYOUT_CSS }).catch(() => {});
  const go = async (path) => { await open(path); await layout(); };

  await layout();
  await card('Портал МЗ РК · кабинет бизнеса', 'Организации',
    'Реестр организаций портала. К организации привязаны учётные записи сотрудников — при её удалении их доступ закрывается.', 5200);

  // ── 1. Реестр ─────────────────────────────────────────────────────
  await section('реестр', async () => {
    await point('Действующие', '[role=tab]');
    await say('Вкладки', 'Действующие и Удалённые. У удалённых добавляется столбец «Дата закрытия»');
    await point('Пользователи', '[role=columnheader]');
    await say('Столбцы', 'БИН и тип, наименование на русском и казахском, число закреплённых пользователей, дата открытия. По 15 записей на странице', 4400);
    await type('#am-search', 'нцэлс', 140);
    await sleep(600);
    await say('Поиск', 'По БИН и наименованию, в том числе по аббревиатуре. «Сбросить» возвращает полный список');
    await click('Сбросить', 'button');
  });

  // ── 2. Создание ───────────────────────────────────────────────────
  await section('создание', async () => {
    await card('Сценарий 1', 'Новая организация', 'БИН → проверка уникальности → автозаполнение из ГБД ЮЛ или ИС КГД.');
    await click('Новая организация', 'button');
    await sleep(600);
    await type('#of-bin', '180540024521');
    await sleep(700);
    await say('Alt 2 · Уже существует', '«Организация с указанным БИН уже существует.» Проверка — сразу после 12 цифр, рядом ссылка на карточку', 4400);
    await clearField('#of-bin');
    await type('#of-bin', '210340012345');
    await waitText('Найдена в ГБД ЮЛ');
    await sleep(500);
    await say('Данные из ГБД ЮЛ', 'Наименования, адреса и виды деятельности на двух языках заполнены. Поля остаются редактируемыми, источник подписан', 4400);
    await show('Фактический адрес совпадает', 'label');
    await say('Адреса', 'Если фактический адрес совпадает с юридическим — одна отметка вместо повторного ввода');
    await point('Дата создания', 'label');
    await say('Дата создания', 'Присваивается автоматически текущей датой');
    await click('Сохранить', '#am-drawer button');
    await waitText('Организация создана');
    await say('Создана', 'Организация во вкладке «Действующие», строка подсвечена. К ней уже можно привязывать пользователей');
  });

  // ── 3. Карточка ───────────────────────────────────────────────────
  await section('карточка', async () => {
    await card('Сценарий 2', 'Карточка организации', 'Режим только просмотра.');
    await type('#am-search', 'ннцрз', 120);
    await sleep(500);
    await click('Национальный научный центр', 'button.name-btn');
    await sleep(800);
    await say('Карточка', 'БИН, наименования на казахском и русском, юридический и фактический адреса, основной и вторичный ОКЭД, даты создания и изменения', 4800);
    await show('Пользователи организации', 'h3');
    await say('Сотрудники', 'Кто закреплён за организацией и переход к ним в раздел «Пользователи»');
    await click('Закрыть', '#am-drawer button');
    await clearField('#am-search');
    await sleep(400);
  });

  // ── 4. Удаление с пользователями ──────────────────────────────────
  await section('удаление', async () => {
    await card('Сценарий 3 · Alt 4', 'Удаление организации с пользователями', 'Организация и её пользователи меняются одной транзакцией.');
    await click('', 'button[aria-label^="Удалить: ТОО «Астана Групп»"]');
    await sleep(700);
    await say('Предупреждение', 'Текст по постановке: за организацией закреплены пользователи, все будут автоматически деактивированы. Продолжить?', 4600);
    await point('Будут деактивированы', 'div');
    await say('Кого это коснётся', 'Список сотрудников прямо в диалоге, а кнопка называет последствие');
    await click('Удалить и деактивировать', '#am-confirm button');
    await waitText('Организация удалена');
    await sleep(400);
    await say('Удалено', 'Статус INACTIVE, дата закрытия — сегодня. Два пользователя деактивированы, вход для них закрыт', 4200);
    await go('Пользователи.dc.html?q=180540024521&tab=inactive');
    await sleep(600);
    await say('Раздел «Пользователи»', 'Сотрудники организации ушли из «Действующих» во «Деактивированные». Личный профиль «Гражданин» того же ИИН не затронут', 4800);
    await point('', 'button[aria-label^="Восстановить"]');
    await say('Восстановление закрыто', 'Пока организация удалена, вернуть её сотрудников нельзя — кнопка объясняет причину');
  });

  // ── 5. Ошибка транзакции ──────────────────────────────────────────
  await section('ошибка транзакции', async () => {
    await go('Организации.dc.html');
    await card('Сценарий 4', 'Ошибка при удалении', 'Если транзакция не прошла — не меняется ничего.');
    await click('Прототип', 'button');
    await click('Ошибка транзакции', 'button');
    await say('Панель прототипа', 'Имитируем сбой сервера при удалении');
    await click('Прототип', 'button');
    await type('#am-search', 'шифа', 120);
    await sleep(400);
    await click('', 'button[aria-label^="Удалить: ТОО «Шифа"]');
    await sleep(500);
    await click('Удалить', '#am-confirm button.btn-d');
    await waitText('Организация не удалена');
    await say('Откат', 'Организация и её пользователи остались без изменений. Поиск и страница сохранены — можно повторить', 4200);
    await click('Прототип', 'button');
    await click('Успех', 'button');
    await click('Прототип', 'button');
    await clearField('#am-search');
  });

  // ── 6. Восстановление ─────────────────────────────────────────────
  await section('восстановление', async () => {
    await card('Сценарий 5', 'Восстановление организации', 'Дата закрытия очищается, пользователей можно вернуть вместе с ней.');
    await click('', '#am-tab-deleted');
    await sleep(500);
    await say('Удалённые', 'Здесь — дата закрытия и просмотр карточки');
    await click('Астана Групп', 'button.name-btn');
    await sleep(800);
    await click('Восстановить', '#am-drawer button');
    await sleep(600);
    await say('Вместе с пользователями', 'Отметка вернёт сотрудников, деактивированных при удалении. Без неё они останутся в «Деактивированных»', 4600);
    await click('Восстановить', '#am-confirm button.btn-p');
    await waitText('Организация восстановлена');
    await say('Восстановлено', 'Организация снова в «Действующих», её сотрудники могут входить в систему');
  });

  await card('Портал МЗ РК · кабинет бизнеса', 'Организации',
    'Реестр, карточка, создание по БИН, удаление с деактивацией пользователей и восстановление.', 4200);
}
