/**
 * Видео «Профиль врача» — по постановке UC1.1 «Реализация профиля медперсонала»
 * и описанию методов sur2_service.
 *
 *   npm run record -- doctor-profile   → exports/video/6. Профиль врача.mp4
 *
 * Вход медработника по ЭЦП → профиль: шапка из ЭЦП, места работы (М1 + БИН из М4),
 * квалификация (М3), образование и трудовая деятельность (М2), обновление;
 * ответы СУР по §7: медленный ответ, СУР недоступен, нет данных по ИИН,
 * сбой одного метода, пустой personalItem, нет БИН;
 * переход из открытого ЭПЗ с подтверждением.
 * Доработки по замечаниям аналитика — отдельным видео: doctor-profile-remarks.
 */

export const title = 'Профиль врача';
export const fileName = '6. Профиль врача';
export const start = 'Вход.dc.html';

export default async function record(ctx) {
  const { page, sleep, caption, say, title: card, click, point, show, type, waitText, open, section } = ctx;

  const PANEL = 'Прототип · ответ СУР';
  /** Переключить ответ СУР в панели «Прототип» (данные перезапрашиваются без перезагрузки). */
  async function scn(label, note) {
    // подпись меняется сразу: старая не должна висеть над новым состоянием экрана
    await caption('Панель «Прототип»', 'Ответ СУР: «' + label + '»');
    await click(PANEL, 'button');
    await sleep(400);
    await click(label, 'button[role=radio]');
    if (note) await say('Панель прототипа', note, 2200);
    await click(PANEL, 'button');
    await sleep(300);
  }
  const top = () => page.evaluate(() => window.scrollTo({ top: 0, behavior: 'smooth' })).then(() => sleep(700));
  const tab = async (name) => { await click(name, '[role=tab]'); await sleep(500); };

  await card('Портал МЗ РК · кабинет медработника', 'Профиль врача',
    'При входе сведения о враче автоматически запрашиваются в СУР по ИИН из ЭЦП и показываются в виде профиля.', 5200);

  // ── 1. Вход ───────────────────────────────────────────────────────
  await section('вход', async () => {
    await open('Вход.dc.html', { reset: true });
    await say('Вход медработника', 'Обычный вход по ЭЦП. После него медработник сразу попадает в «Профиль врача»');
    await click('Войти с ЭЦП', 'button');
    await waitText('Выберите сертификат ЭЦП');
    await caption('Ключ ЭЦП', 'Тестовый ключ медработника: Ахметов Серик Кайратович, городская поликлиника № 4');
    await sleep(1200);
    await click('990140002374', '.ecp-item');
    await waitText('Введите пароль');
    await sleep(800);
    await type('#login-pass', 'Demo#2026');
    await click('Войти', 'button[type=submit]');
    await waitText('Профиль врача', 15000);
    await sleep(600);
  });

  // ── 2. Шапка профиля ──────────────────────────────────────────────
  await section('шапка', async () => {
    await caption('Загрузка', 'Методы 1–3 СУР запрашиваются параллельно, пока идёт ответ — заготовки вместо данных');
    await waitText('Обновлено сегодня', 15000);
    await sleep(900);
    await point('Профиль врача', 'a.dn-it');
    await say('Меню', 'Порядок разделов по замечанию аналитика: 1 — Профиль врача, 2 — Электронный паспорт здоровья');
    await point('Ахметов Серик Кайратович', '.pf-fio');
    await say('Из ЭЦП', 'ФИО и ИИН берутся из сессии авторизации');
    await click('', 'button[aria-label="Скопировать ИИН"]');
    await say('Копирование', 'ИИН, БИН и регистрационные номера копируются одним нажатием', 2400);
    await point('Обновлено сегодня', '.pf-sync div');
    await say('Синхронизация', 'Время последнего обновления сведений из СУР');
    await point('Если данные неверны', '.pf-herofoot span');
    await say('Только просмотр', 'Данные ведёт отдел кадров в СУР — подсказка, куда обращаться, если они неверны');
  });

  // ── 3. Места работы ───────────────────────────────────────────────
  await section('места работы', async () => {
    await card('Метод 1 + метод 4', 'Места работы', 'GetMoFpPersonalIin — все места работы списком; GetMoInfoItems — БИН каждой организации одним запросом.');
    await show('Текущие места работы', 'h2', 'start');
    await point('Работает', '.pf-badge');
    await say('Статусы', '«Работает» — зелёный, «В отпуске» — жёлтый. Прежние места — во вкладке «Трудовая деятельность»');
    await point('БИН 990140002374', '.pf-bin');
    await say('БИН из метода 4', 'Показывается у каждого места работы — БИН из ЭЦП покрывает только одну организацию');
    await show('Тип персонала', '.pf-dt');
    await say('Все поля постановки', 'Должность, специальность, ставки, тип и категория должности, вид внештатной работы, дата приёма', 4000);
    await top();
  });

  // ── 4. Квалификация ───────────────────────────────────────────────
  await section('квалификация', async () => {
    await card('Метод 3', 'Квалификация и сертификаты', 'QualificationByIin — только активные записи (enabled = true).');
    await point('истекает через', '[role=status]');
    await say('Предупреждение', 'Если сертификат истекает в ближайшие 90 дней — заметная плашка вверху профиля');
    await click('Открыть сертификат', 'button');
    await sleep(900);
    await say('Сертификат', 'Специальность, статус из СУР, категория, срок действия, регистрационный номер и даты', 3600);
    await show('Функциональная диагностика', 'h3');
    await point('Бессрочный', '.pf-chip');
    await say('Бессрочный', 'Если признак бессрочности — дата окончания не показывается');
    await top();
  });

  // ── 5. Образование ────────────────────────────────────────────────
  await section('образование', async () => {
    await card('Метод 2', 'Образование', 'GetEducation — первичное образование и последипломная подготовка.');
    await tab('Образование');
    await show('Первичное образование', 'h2', 'start');
    await say('Первичное образование', 'Специальность по диплому, ВУЗ, номер и даты диплома');
    await show('Последипломная подготовка', 'h2', 'start');
    await say('Интернатура и резидентура', 'Вид подготовки, организация, период с длительностью, номер свидетельства');
    await top();
  });

  // ── 6. Трудовая деятельность ──────────────────────────────────────
  await section('трудовая деятельность', async () => {
    await tab('Трудовая деятельность');
    await point('Стаж в организациях здравоохранения', 'div');
    await say('Стаж', 'Считается по периодам из СУР. Совместительство в одно время учитывается один раз');
    await show('История занятости', 'h2', 'start');
    await say('История занятости', 'Периоды от новых к старым, в том числе прежние места работы; текущие отмечены зелёным');
    await top();
    await tab('Места работы');
  });

  // ── 7. Обновление ─────────────────────────────────────────────────
  await section('обновление', async () => {
    await caption('Обновить', 'Сведения перезапрашиваются в СУР, уже показанные данные не пропадают');
    await click('Обновить', '.pf-sync button');
    await waitText('Данные профиля обновлены');
    await say('Готово', 'Подтверждение внизу справа, время обновления в шапке профиля', 3000);
  });

  // ── 8. Ответы СУР ─────────────────────────────────────────────────
  await section('медленный ответ', async () => {
    await card('§7 постановки', 'Ответы СУР и ошибки', 'Сценарии переключаются в панели «Прототип» слева внизу.');
    await scn('Медленный ответ');
    await say('Загрузка', 'Пока СУР отвечает, профиль не пустой: ФИО и ИИН уже есть, вместо данных — заготовки', 2600);
    await waitText('Обновлено сегодня', 15000);
    await sleep(800);
  });

  await section('СУР недоступен', async () => {
    await scn('СУР недоступен');
    await waitText('Не удалось загрузить данные профиля', 8000);
    await sleep(500);
    await say('СУР недоступен', '«Не удалось загрузить данные профиля. Повторите попытку позже.» Профиль и кабинет не блокируются', 4200);
    await point('Перейти в ЭПЗ', 'a');
    await say('Можно работать дальше', 'Кнопки «Повторить» и «Перейти в ЭПЗ»');
  });

  await section('некорректный ответ', async () => {
    await scn('Некорректный ответ');
    await waitText('Не удалось загрузить данные профиля', 8000);
    await say('Некорректный ответ', 'Ошибка логируется, пользователю — то же общее сообщение', 2600);
  });

  await section('нет данных', async () => {
    await scn('Нет данных по ИИН');
    await waitText('не найдены в СУР', 8000);
    await sleep(500);
    await say('Нет данных по ИИН', '«Сведения о сотруднике не найдены в СУР.» и «Проверить снова»', 3600);
  });

  await section('сбой метода', async () => {
    await scn('Сбой метода квалификации');
    await waitText('Обновлено сегодня', 8000).catch(() => {});
    await sleep(1200);
    await tab('Квалификация');
    await say('Частичный сбой', 'Если не ответил один метод — ошибка и «Повторить» только в его вкладке, остальные разделы работают', 4200);
    await tab('Места работы');
  });

  await section('нет мест работы', async () => {
    await scn('Нет мест работы');
    await sleep(1600);
    await point('Квалификация', '[role=tab]');
    await say('Пустой personalItem', 'Блок «Место работы» не отображается — профиль открывается с квалификации', 3400);
  });

  await section('нет БИН', async () => {
    await scn('БИН не получен (М4)');
    await sleep(1800);
    await show('Медицинский центр Шипагер', 'h3');
    await say('Метод 4 без ответа', 'БИН этого места работы не показывается, остальные сведения — без изменений', 3600);
    await top();
  });

  await section('все сведения', async () => {
    await scn('Все сведения');
    await sleep(1400);
  });

  // ── 9. Переход из открытого ЭПЗ ───────────────────────────────────
  await section('переход из ЭПЗ', async () => {
    await card('Навигация', 'Переход из открытого ЭПЗ', 'Уход из ЭПЗ пациента закрывает сессию доступа — поэтому сначала подтверждение.');
    await click('Электронный паспорт здоровья', 'a.dn-it');
    await waitText('Введите ИИН пациента');
    await sleep(800);
    await click('Иванова А.С.', 'button');
    await waitText('Симулировать согласие пациента');
    await click('Симулировать согласие пациента', 'button');
    await waitText('Открыть ЭПЗ пациента');
    await click('Открыть ЭПЗ пациента', 'button');
    await sleep(1400);
    await say('ЭПЗ открыт', 'Идёт 30-минутная сессия доступа к данным пациента');
    await click('Профиль врача', 'a.dn-it');
    await waitText('Завершить просмотр ЭПЗ?');
    await sleep(500);
    await say('Подтверждение', 'Сессия будет закрыта — для повторного доступа понадобится новое согласие пациента', 3800);
    await click('Остаться', 'button');
    await say('Остаться', 'Врач продолжает работу с ЭПЗ без потери сессии', 2400);
    await click('Профиль врача', 'a.dn-it');
    await sleep(500);
    await click('Завершить и перейти', 'button');
    await waitText('Обновлено сегодня', 15000);
    await sleep(1500);
  });

  await card('Портал МЗ РК', 'Профиль врача', 'Адаптирован под широкие мониторы, ноутбуки, планшеты (меню иконками) и телефоны (меню внизу).', 4400);
}
