/**
 * Видео «Кабинет гражданина — прикрепление к поликлинике и «Мои заявки»» по постановке
 * «Прикрепление к поликлинике» (09.11.2026).
 *
 *   npm run record -- citizen-attach --voice --tts=edge --no-subs
 *     → exports/video/28. Кабинет гражданина — прикрепление к поликлинике и «Мои заявки».mp4
 *
 * Услуги кабинета → паспорт услуги → мастер из 6 шагов: ребёнок из общего списка, каскад регионов
 * (область — 4 уровня, город — 2), поиск медорганизации, подсказка «Далее», врачи и участки,
 * причина, проверка с «Изменить» и «К проверке данных», подпись ЭЦП → карточка заявки со всеми статусами →
 * «Мои заявки»: фильтры по статусу и периоду, сортировка, переход в карточку.
 * Панели «Прототип» в записи скрыты, ответы сервиса переключаются за кадром.
 */

export const title = 'Кабинет гражданина — прикрепление к поликлинике и «Мои заявки»';
export const fileName = '28. Кабинет гражданина — прикрепление к поликлинике и «Мои заявки»';
export const start = 'Услуги гражданина.dc.html';
export const voice = true;
// самый частый размер ноутбука (1920×1080 при масштабе 125 %)
export const viewport = { width: 1536, height: 864 };

export default async function record(ctx) {
  const { page, sleep, say, title: card, click, point, type, clearField, waitText, open, section } = ctx;

  // В записи нет панелей «Прототип»
  const prep = () => page.addStyleTag({ content: '.at-pp,.rq-pp,.su-pp{display:none!important}' }).catch(() => {});
  const go = async (path) => { await open(path); await prep(); await sleep(300); };
  const top = () => page.evaluate(() => window.scrollTo({ top: 0, behavior: 'smooth' })).then(() => sleep(700));
  const next = async () => { await click('', '.at-foot-r .at-btn'); await sleep(900); };
  // Навести настоящий указатель — чтобы показалась подсказка
  const hover = async (text, sel) => {
    await point(text, sel);
    const box = await page.evaluate((a) => {
      const el = [...document.querySelectorAll(a[1])].find((n) => n.getClientRects().length && (!a[0] || n.innerText.includes(a[0])));
      if (!el) return null; const r = el.getBoundingClientRect(); return { x: r.left + r.width / 2, y: r.top + r.height / 2 };
    }, [text, sel]);
    if (box) await page.mouse.move(box.x, box.y);
    await sleep(700);
  };
  const unhover = async () => { await page.mouse.move(6, 420); await sleep(200); };
  const pick = async (field, option) => {
    await click('', '#at-sel-' + field);
    await sleep(600);
    await click(option, '.at-pop-o');
    await sleep(700);
  };
  const setStatus = async (num, st) => {
    await page.evaluate((a) => window.mpAttach && window.mpAttach.setStatus(a[0], a[1]), [num, st]);
    await sleep(900);
  };

  await prep();
  await card('Портал МЗ РК · личный кабинет гражданина', 'Прикрепление к поликлинике',
    'Новая услуга кабинета: подача запроса на прикрепление, статусы обработки и раздел «Мои заявки».', 5600,
    'Прикрепление к поликлинике. Новая услуга личного кабинета: подача запроса на прикрепление, статусы обработки и раздел «Мои заявки».');

  // ── 1. Услуги кабинета → паспорт ──────────────────────────────────
  await section('услуги', async () => {
    await waitText('Прикрепление к поликлинике', 15000);
    await sleep(500);
    await point('Прикрепление к поликлинике', '.su-row');
    await say('Услуги', 'Услуга оказывается на портале: открывается в кабинете, а не на eGov', 4000,
      'В разделе «Услуги» прикрепление к поликлинике теперь оказывается прямо на портале — в личном кабинете, без перехода на сторонний сайт.');
    await click('Прикрепление к поликлинике', '.su-row');
    await waitText('Порядок оказания услуги', 15000);
    await prep();
    await sleep(900);
    await say('Паспорт услуги', 'Порядок из шести шагов, сведения, НПА и информация об услуге', 3600,
      'Открывается паспорт услуги. Шесть шагов из постановки собраны в компактную сетку — почти без прокрутки.');
    await hover('Свидетельство о рождении', '.ps-doc');
    await say('Сведения', 'Документы прикладывать не нужно — портал получает их сам', 3600,
      'Документы прикладывать не нужно: удостоверение личности, свидетельство о рождении и документы опеки портал получает сам. Пояснения — во всплывающих подсказках.');
    await unhover();
    await point('Срок оказания', '.ps-fact');
    await say('Информация об услуге', 'Справа — услугодатель, получатели, срок, результат и стоимость', 3400,
      'Справа закреплена информация об услуге: услугодатель, получатели, срок — один рабочий день, результат и стоимость.');
    await click('Подать заявку', '.ps-btn');
    await waitText('На кого необходимо оформить', 15000);
    await prep();
    await sleep(900);
  });

  // ── 2. Шаг 1 — заявитель ──────────────────────────────────────────
  await section('шаг 1', async () => {
    await say('Подача заявки', 'Шесть шагов, вопрос каждого шага — дословно из постановки', 3400,
      'Подача заявки идёт в шесть шагов. Вопрос каждого шага — дословно из постановки.');
    await point('Заявитель', '.at-si');
    await say('Ход заполнения', 'Справа — шаги и уже выбранные значения', 3200,
      'Справа всегда видно, на каком шаге вы находитесь и что уже выбрано.');
    await point('На себя', '.at-tile');
    await say('На себя', 'ИИН берётся из авторизации, повторно вводить не нужно', 3200,
      'Если прикрепляетесь сами, индивидуальный идентификационный номер берётся из авторизации — вводить его повторно не нужно.');
    await click('На ребёнка', '.at-tile');
    await waitText('Сейтжанов Алихан', 15000);
    await sleep(500);
    await say('На ребёнка', 'Два сервиса параллельно — дети и подопечные одним списком', 4200,
      'При подаче на ребёнка портал одновременно запрашивает сведения о детях и о подопечных и показывает их одним списком: фамилия, имя, отчество и дата рождения.');
    await click('Сейтжанов Алихан', '.at-opt');
    await sleep(400);
    await next();
    await waitText('Выберите регион', 8000);
    await sleep(500);
  });

  // ── 3. Шаг 2 — регион ─────────────────────────────────────────────
  await section('шаг 2', async () => {
    await point('Сейтжанов Алихан', '.at-si');
    await say('Выбор сохранён', 'Выбранный ребёнок — в ходе заполнения справа', 2800,
      'Выбранный ребёнок сразу появился справа.');
    await click('', '#at-sel-0');
    await sleep(700);
    await say('Регион', 'Города республиканского значения и области — группами', 3000,
      'Регион выбирается из справочника: города республиканского значения и области — отдельными группами.');
    await click('Акмолинская область', '.at-pop-o');
    await sleep(800);
    await say('Следующий уровень', 'Поле района появляется только после выбора региона', 3000,
      'Следующий уровень появляется только после выбора предыдущего.');
    await pick(1, 'Аккольский район');
    await sleep(900);
    await say('Область — четыре уровня', 'Район, сельский округ, населённый пункт; единственный вариант выбирается сам', 4400,
      'Для области уровней четыре: район, сельский округ и населённый пункт. Если вариант на уровне один, он выбирается сам — меньше кликов.');
    await pick(0, 'г. Астана');
    await sleep(500);
    await say('Город — два уровня', 'Для города республиканского значения — только район города', 3200,
      'Для города республиканского значения уровней два: город и район.');
    await pick(1, 'район Есиль');
    await sleep(300);
    await next();
    await waitText('Выберите медицинскую организацию', 8000);
    await sleep(1300);
  });

  // ── 4. Шаг 3 — медорганизация ─────────────────────────────────────
  await section('шаг 3', async () => {
    await say('Медицинская организация', 'Организации выбранной территории: наименование и адрес', 3200,
      'Список медицинских организаций выбранной территории: полное наименование и адрес.');
    await type('.at-search input', '16', 220);
    await sleep(700);
    await say('Поиск', 'По названию или адресу, совпадение подсвечено', 2800,
      'Поиск по названию или адресу, совпадение подсвечено.');
    await clearField('.at-search input');
    await sleep(500);
    await hover('', '.at-foot-r .at-btn');
    await say('Подсказка', 'Пока ничего не выбрано, «Далее» объясняет причину в подсказке', 3400,
      'Пока организация не выбрана, кнопка «Далее» неактивна, а причина — во всплывающей подсказке.');
    await click('', '.at-foot-r .at-btn');
    await sleep(700);
    await say('Подсветка', 'Нажатие подсвечивает то, что нужно выбрать', 2800,
      'Если всё же нажать, список подсвечивается — сразу понятно, что выбрать.');
    await unhover();
    await click('Городская поликлиника №11', '.at-opt');
    await sleep(400);
    await next();
    await waitText('Выберите медицинского работника', 8000);
    await sleep(1300);
  });

  // ── 5. Шаг 4 — медработник и участок ──────────────────────────────
  await section('шаг 4', async () => {
    await say('Медицинский работник', 'Ф.И.О., номер участка, прикреплённое население и доступность', 4000,
      'Медицинские работники и участки: фамилия, номер участка, количество прикреплённого населения и статус доступности.');
    await point('Недоступно', '.at-doc');
    await say('Недоступно', 'Закрытый для прикрепления участок выбрать нельзя', 2800,
      'Участок, закрытый для прикрепления, выбрать нельзя.');
    await click('Искакова', '.at-doc');
    await sleep(400);
    await next();
    await waitText('Укажите причину прикрепления', 8000);
    await sleep(900);
  });

  // ── 6. Шаг 5 — причина ────────────────────────────────────────────
  await section('шаг 5', async () => {
    await say('Причина', 'Варианты — из справочника сервиса', 2600,
      'Причина прикрепления — из справочника сервиса.');
    await click('Переезд', '.at-tile');
    await sleep(400);
    await next();
    await waitText('Проверьте данные перед подписанием', 8000);
    await sleep(900);
  });

  // ── 7. Шаг 6 — проверка и подпись ─────────────────────────────────
  await section('шаг 6', async () => {
    await say('Проверка', 'Заявитель, регион, организация с адресом, медработник с участком, причина', 4400,
      'Перед подписанием — сводка: заявитель с датой рождения, регион, медицинская организация с адресом, медицинский работник с номером участка и причина.');
    await click('Изменить', '.at-rv-r:last-child .at-link');
    await waitText('Укажите причину прикрепления', 8000);
    await sleep(600);
    await click('Свободное прикрепление', '.at-tile');
    await sleep(300);
    await point('К проверке данных', '.at-foot-r .at-btn');
    await say('Изменить', 'После правки — сразу обратно к проверке, без повторного прохода шагов', 3800,
      'У каждой строки есть «Изменить». После правки кнопка ведёт сразу обратно к проверке — проходить шаги заново не нужно.');
    await click('К проверке данных', '.at-foot-r .at-btn');
    await waitText('Проверьте данные перед подписанием', 8000);
    await sleep(800);
    await click('Подписать и отправить', '.at-foot-r .at-btn');
    await waitText('Пароль от хранилища', 8000);
    await sleep(600);
    await say('Подписание', 'Запрос подписывается ЭЦП', 2600,
      'Запрос подписывается электронной цифровой подписью.');
    await type('#sg-pwd', '1', 160);
    await sleep(300);
    await click('Открыть', '.sg-btn');
    await waitText('Выберите сертификат', 8000);
    await sleep(700);
    await click('Подписать', '.sg-btn.sg-p');
    await waitText('Сведения о заявке', 20000);
    await prep();
    await sleep(1200);
  });

  // ── 8. Карточка заявки и статусы ──────────────────────────────────
  let num = '';
  await section('карточка', async () => {
    num = await page.evaluate(() => new URL(location.href).searchParams.get('n') || '');
    await say('Заявка отправлена', 'Открылась карточка: номер, статус «В обработке» и сообщение постановки', 4000,
      'Запрос отправлен, и открылась карточка заявки: номер, статус «В обработке» и сообщение из постановки.');
    await point('Сведения о заявке', '.rq-card-h');
    await say('Сведения', 'Дата и время подачи, заявитель, причина, организация, медработник', 3400,
      'Ниже сведения о заявке: дата и время подачи, заявитель, причина, организация и медицинский работник.');
    await click('Проверить статус', '.rq-btn');
    await sleep(1500);
    await say('Проверить статус', 'Запрос статуса; время обновления — рядом', 3000,
      'Кнопка «Проверить статус» запрашивает актуальный статус, время последнего обновления — рядом.');
    await setStatus(num, 'APPROVED');
    await say('Прикрепление выполнено', 'Организация, врач, участок и дата завершения прикрепления', 4200,
      'Прикрепление выполнено: сообщение, медицинская организация, врач, номер участка и дата завершения прикрепления. Каждое значение показано один раз.');
    await setStatus(num, 'REJECTED');
    await say('Отказано', 'Отображается дата получения отказа', 2600,
      'При отказе отображается дата получения отказа.');
    await setStatus(num, 'ERROR');
    await say('Техническая ошибка', 'Сообщение и возможность проверить статус позднее', 3400,
      'При технической ошибке — сообщение из постановки и возможность проверить статус позднее.');
    await setStatus(num, 'IN_PROGRESS');
  });

  // ── 9. Мои заявки ─────────────────────────────────────────────────
  await section('мои заявки', async () => {
    await top();
    await point('Мои заявки', '.cn-nav a');
    await say('Мои заявки', 'Новый пункт меню кабинета', 2600,
      'В меню кабинета появился новый раздел — «Мои заявки».');
    await click('Мои заявки', '.cn-nav a');
    await waitText('Заявитель', 15000);
    await sleep(1200);
    await say('Список заявок', 'Поданные пользователем запросы; новая заявка — сверху', 3400,
      'Здесь все запросы на прикрепление, поданные пользователем. Новая заявка — первой.');
    await point('Обновлено', '.mr-upd');
    await say('Обновление статуса', 'Под статусом — дата и время последнего обновления', 3000,
      'Под статусом — дата и время его последнего обновления.');
    await click('Прикрепление выполнено', '.mr-chip');
    await sleep(900);
    await say('Фильтр по статусу', 'Кнопки со счётчиками — один клик, без «Применить»', 3400,
      'Фильтр по статусу — кнопками со счётчиками. Срабатывает сразу, без кнопки «Применить».');
    await click('Все', '.mr-chip');
    await sleep(500);
    await click('', '.mr-per-btn');
    await sleep(600);
    await click('За 3 месяца', '.mr-po');
    await sleep(900);
    await say('Период подачи', 'Готовые периоды или свои даты с — по', 3200,
      'Период подачи: готовые варианты или свои даты.');
    await click('', '.mr-per-x');
    await sleep(700);
    await click('Статус', '.mr-sort');
    await sleep(800);
    await say('Сортировка', 'По номеру, дате подачи и статусу', 2600,
      'Список сортируется по номеру, дате подачи и статусу.');
    await click('Дата подачи', '.mr-sort');
    await sleep(800);
    await click('Сейтжанов Алихан', '.mr-tbl tbody tr');
    await waitText('Сведения о заявке', 15000);
    await prep();
    await sleep(1200);
    await say('Карточка', 'Строка открывает карточку заявки', 2600,
      'По строке открывается карточка заявки.');
  });

  await card('Готово к проверке', 'Прикрепление к поликлинике и «Мои заявки»',
    'Личный кабинет → Услуги → «Прикрепление к поликлинике». Пароль ЭЦП в прототипе — 1.', 5200,
    'Готово к проверке. Личный кабинет, раздел «Услуги», «Прикрепление к поликлинике». Пароль электронной подписи в прототипе — единица.');
}
