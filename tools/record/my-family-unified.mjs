/**
 * Видео «Моя семья — единый список детей» по постановке «Объединение детей в разделе „Моя семья“».
 *
 *   npm run record -- my-family-unified --voice --tts=edge --no-subs
 *     → exports/video/30. Моя семья — единый список детей.mp4
 *
 * Пустой раздел → окно «Добавление детей» (загрузка, единый список, выбор, «Выбрать всех» / «Снять выбор»)
 * → сохранение → карточки одного вида → «Уже добавлен» → все добавлены → ошибка и «Повторить» →
 * нет доступных детей → ЭПЗ ребёнка. Ответ сервиса переключается за кадром — панель «Прототип» скрыта.
 */

export const title = 'Моя семья — единый список детей';
export const fileName = '30. Моя семья — единый список детей';
export const start = 'Личный кабинет.dc.html';
export const voice = true;
// ноутбук 15–16″ (1920×1080 при масштабе 125 %)
export const viewport = { width: 1536, height: 864 };

export default async function record(ctx) {
  const { page, sleep, say, title: card, click, point, at, open, waitText, section } = ctx;

  const prep = () => page.addStyleTag({ content: '.pp{display:none!important}' }).catch(() => {});
  const scn = (v) => page.evaluate((x) => sessionStorage.setItem('mp-family-scn', x), v);
  /** Настоящая мышь — для hover-состояний */
  const hover = async (text, sel, wait = 700) => {
    const box = await page.evaluate(([t, s]) => {
      const el = [...document.querySelectorAll(s)].find((n) => n.getClientRects().length && (!t || n.innerText.includes(t)));
      if (!el) return null; const r = el.getBoundingClientRect(); return { x: Math.round(r.left + r.width / 2), y: Math.round(r.top + r.height / 2) };
    }, [text, sel]).catch(() => null);
    if (!box) return;
    await at(box.x, box.y);
    await sleep(400);
    try { await page.mouse.move(box.x, box.y, { steps: 8 }); } catch (e) {}
    await sleep(wait);
  };
  const away = async () => { try { await page.mouse.move(1500, 160, { steps: 4 }); } catch (e) {} await sleep(150); };
  const openAdd = async () => { await click('Добавить ребёнка', '.fm-head .fm-btn'); await sleep(300); };

  await card('Портал МЗ РК · личный кабинет гражданина', 'Моя семья — единый список детей',
    'Родные и опекаемые дети — в одном списке, без деления по типу родства или опеки.', 5200,
    'Моя семья. Родные и опекаемые дети теперь в одном общем списке, без деления по типу родства или опеки.');

  // ── 1. Пустой раздел ──────────────────────────────────────────────
  await section('пустой раздел', async () => {
    await prep();
    await page.evaluate(() => { localStorage.removeItem('mp-family'); sessionStorage.removeItem('mp-family-scn'); });
    await point('Моя семья', '.cn-nav a');
    await say('Меню кабинета', 'Раздел «Моя семья»', 2400,
      'Открываем раздел «Моя семья» в личном кабинете гражданина.');
    await click('Моя семья', '.cn-nav a');
    await waitText('Вы пока не добавили детей', 15000);
    await prep();
    await sleep(500);
    await point('Вы пока не добавили детей', '.fm-empty-t');
    await say('Пустой раздел', '«Вы пока не добавили детей» и кнопка «Добавить ребёнка»', 3200,
      'Пока детей нет, раздел показывает надпись «Вы пока не добавили детей» и одну кнопку «Добавить ребёнка».');
  });

  // ── 2. Окно: загрузка и единый список ─────────────────────────────
  await section('окно до выбора', async () => {
    await click('Добавить ребёнка', '.fm-empty .fm-btn');
    await sleep(250);
    await say('Загрузка сведений', 'Каркас списка на своём месте, пока сведения загружаются', 1200,
      'Открывается окно «Добавление детей». Пока сведения загружаются, на месте списка — его каркас.');
    await waitText('Выбрать всех', 8000);
    await sleep(400);
    await say('Единый список', 'Без вкладок и группировки: чекбокс, ФИО, ИИН и дата рождения', 3600,
      'Все дети, доступные для добавления, — одним списком, без вкладок и группировки по типу связи. У каждого ребёнка: чекбокс, фамилия, имя, отчество, индивидуальный идентификационный номер и дата рождения.');
    await point('Добавить выбранных', '.fm-df .fm-btn.pri');
    await say('До выбора', 'Кнопка «Добавить выбранных (0)» неактивна', 2800,
      'Пока никто не выбран, кнопка «Добавить выбранных» неактивна.');
  });

  // ── 3. Выбор ──────────────────────────────────────────────────────
  await section('выбор', async () => {
    await click('Сейтжанов Алихан Даниярович', '.fm-opt');
    await sleep(300);
    await say('После выбора', 'Строка выделена, на кнопке — число выбранных', 2800,
      'Нажатие на строку отмечает ребёнка. Кнопка становится активной и показывает, сколько детей выбрано.');
    await click('Выбрать всех', '.fm-lh');
    await sleep(400);
    await say('Выбрать всех', 'Отмечает всех доступных детей одним нажатием', 2600,
      'Выбрать всех — отмечает всех детей одним нажатием.');
    await click('Снять выбор', '.fm-clr');
    await sleep(400);
    await say('Снять выбор', 'Сбрасывает выбор; ссылка видна, только когда кто-то выбран', 2800,
      'Снять выбор — сбрасывает отметки. Эта ссылка появляется, только когда кто-то выбран.');
    await click('Сейтжанов Алихан Даниярович', '.fm-opt');
    await click('Куанышев Арман Бауржанович', '.fm-opt');
    await sleep(300);
    await say('Родной и опекаемый', 'В списке они ничем не отличаются', 2600,
      'Выбираем двоих детей: одного родного и одного опекаемого. В списке они ничем не отличаются.');
  });

  // ── 4. Сохранение и общий список ──────────────────────────────────
  await section('сохранение', async () => {
    await click('Добавить выбранных (2)', '.fm-df .fm-btn.pri');
    await waitText('Добавлено 2 ребёнка', 6000);
    await sleep(300);
    await say('Сохранение', 'Окно закрылось, новые карточки подсвечены, внизу — уведомление', 3200,
      'После сохранения окно закрывается, дети сразу появляются в общем списке, новые карточки подсвечиваются.');
    await sleep(800);
    await point('Сейтжанов Алихан Даниярович', '.fm-card');
    await say('Карточка ребёнка', 'ФИО, ИИН, дата рождения и возраст, кнопка «ЭПЗ ребёнка»', 3400,
      'Карточки одного вида: фамилия, имя, отчество, идентификационный номер, дата рождения и возраст, и кнопка перехода к электронному паспорту здоровья ребёнка.');
    await point('Куанышев Арман Бауржанович', '.fm-card');
    await say('Без типа связи', 'Нет подписей «Сын», «Дочь», «Подопечный» и значков типа связи', 3400,
      'Подписей «Сын», «Дочь», «Подопечный» и значков типа связи нет — родные и опекаемые выглядят одинаково.');
    await hover('ЭПЗ ребёнка', '.fm-card .fm-btn', 500);
    await away();
  });

  // ── 5. Уже добавленные ────────────────────────────────────────────
  await section('уже добавлен', async () => {
    await openAdd();
    await waitText('Уже добавлен', 8000);
    await sleep(400);
    await point('Уже добавлен', '.fm-tag');
    await say('Уже добавлен', 'Добавленные — внизу списка, с меткой, выбрать повторно нельзя', 3400,
      'Уже добавленные дети опускаются вниз списка с меткой «Уже добавлен». Выбрать их повторно нельзя.');
    await click('Выбрать всех', '.fm-lh');
    await sleep(400);
    await say('Выбрать всех', 'Отмечены только доступные — «Добавить выбранных (3)»', 2800,
      'Выбрать всех отмечает только тех, кого ещё нет в разделе.');
    await click('Добавить выбранных (3)', '.fm-df .fm-btn.pri');
    await waitText('Добавлено 3 ребёнка', 6000);
    await sleep(900);
    await say('Общий список', 'Пять детей одним списком — от старшего к младшему', 3000,
      'Теперь в разделе пять детей — одним списком, от старшего к младшему.');
  });

  // ── 6. Нет доступных: все добавлены ───────────────────────────────
  await section('все добавлены', async () => {
    await openAdd();
    await waitText('Все дети уже добавлены', 8000);
    await sleep(400);
    await say('Нет детей для добавления', 'Если все уже добавлены — «Все дети уже добавлены»', 3000,
      'Если добавлять больше некого, окно так и сообщает: «Все дети уже добавлены».');
    await click('Закрыть', '.fm-df .fm-btn');
    await sleep(500);
  });

  // ── 7. Ошибка загрузки ────────────────────────────────────────────
  await section('ошибка', async () => {
    await scn('fail');
    await openAdd();
    await waitText('Не удалось загрузить сведения', 8000);
    await sleep(400);
    await say('Ошибка загрузки', '«Не удалось загрузить сведения» и кнопка «Повторить»', 3000,
      'Если сведения не загрузились — сообщение об ошибке и кнопка «Повторить».');
    await scn('none');
    await click('Повторить', '.fm-state .fm-btn');
    await waitText('Нет детей, доступных для добавления', 8000);
    await sleep(400);
    await say('Нет доступных детей', 'Сервис не вернул ни одного ребёнка', 2800,
      'А если сервис не нашёл ни одного ребёнка — «Нет детей, доступных для добавления».');
    await click('Закрыть', '.fm-df .fm-btn');
    await scn('ok');
    await sleep(500);
  });

  // ── 8. ЭПЗ ребёнка ────────────────────────────────────────────────
  await section('ЭПЗ ребёнка', async () => {
    await page.evaluate(() => {
      const c = [...document.querySelectorAll('.fm-card')].find((n) => n.innerText.includes('Куанышев Арман'));
      c && c.querySelector('.fm-btn').setAttribute('data-rec', '1');
    });
    await click('ЭПЗ ребёнка', '[data-rec="1"]');
    await waitText('Национальный календарь прививок', 15000);
    await prep();
    await sleep(1600);
    await say('ЭПЗ ребёнка', 'Переход из карточки — электронный паспорт здоровья ребёнка', 3000,
      'Из карточки открывается электронный паспорт здоровья ребёнка. Тип родства или опеки здесь тоже не показывается.');
    await click('Назад в раздел', '.ez-back');
    await waitText('Моя семья', 15000);
    await prep();
    await sleep(1200);
  });

  await card('Портал МЗ РК', 'Моя семья — единый список детей',
    'Раздел растягивается по ширине экрана — от ноутбука 14″ до монитора 27″.', 4400,
    'Раздел «Моя семья» готов. Он аккуратно выглядит и на ноутбуках, и на больших мониторах.');
}
